def test_eta_polar_proof_and_model_paths(lean):
    doc = {"units": [unit("u1", 0, "asserted", U("reviewed", "atlas")), unit("u5", 2, "question", polar(U("reviewed", "atlas")))]}
    r = elaborate(F0(), doc)
    yes = certificate(F0(), r["premises"], ["and", ["top"], U("reviewed", "atlas")], r["environment_id"])
    assert answer(F0(), doc, "u5", answer="yes", evidence={"certificate": yes})["answer"].startswith(
        "supported yes (certificate; premises: UNKNOWN")
    assert certificate(F0(), r["premises"], ["and", ["top"], ["not", U("reviewed", "atlas")]], r["environment_id"],
                       max_steps=2000) is None
