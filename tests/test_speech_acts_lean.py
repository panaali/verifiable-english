"""The Lean `ve_speech_acts_route` on hand-written fixtures of speech-acts.md section 9.

Commands and questions are regenerated by Lean from the decoded units; the
Python tableau prover is used only as an untrusted certificate search over the
premise lists Lean regenerates (`speech-elaborate` returns them with the
environment id), and every certificate is replayed by the Lean checker.
The cross-language comparisons live in test_speech_acts_conformance.py.
"""
from __future__ import annotations

import copy
import json
import shutil
import subprocess
from pathlib import Path

import pytest

from ve.ast import _Decoder
from ve.entailment import prove_entailment
from ve.environment import Environment
from ve.wire import digest

ROOT = Path(__file__).resolve().parents[1]
LEAN = ROOT / "lean/.lake/build/bin/ve_speech_acts_route"
LANGUAGE, REVISION = "ve.core@0.2", "ve-v0.2-expand2-2026-09-25"


@pytest.fixture(scope="module")
def lean():
    if not LEAN.exists():
        lake = shutil.which("lake")
        if lake is None:
            pytest.skip("lake is required for the speech-acts Lean route")
        built = subprocess.run([lake, "build"], cwd=ROOT / "lean", capture_output=True, text=True, timeout=600)
        assert built.returncode == 0, built.stdout + built.stderr
    return LEAN


def run(cases):
    result = subprocess.run([str(LEAN), "-"], input=json.dumps(cases), capture_output=True, text=True, timeout=600)
    return json.loads(result.stdout)


def run1(case):
    [result] = run([case])
    return result


def regulated(role, default, act, permission=None):
    reg = {"role": role, "default": default, "act": act}
    if permission:
        reg["permission"] = permission
    return reg


def F0(task="t1", addressee=("user", "alice"), definites=None, extra_profiles=()):
    """F0 of section 9 (constants lower-case, as the vocabulary requires; the proof-task act reads
    `{0} submit a proof of {1}` because W1's act linter reserves `for`)."""
    if definites is None:
        definites = {"the token": "token1", "the desk": "desk1", "the writing desk": "desk1"}
    base = {"reviewed": ["service"], "cat": ["thing"], "animal": ["thing"], "disabled": ["control"],
            "done_click": ["user", "control"], "done_open": ["user", "desk"], "done_submit": ["user", "query"]}
    preds = {p: {"arguments": a, "description": p} for p, a in base.items()}
    for name, args, reg in [
            ("click_required", ["user", "control"], regulated("obligation", "deny", "{0} click {1}", "click_permitted")),
            ("click_permitted", ["user", "control"], regulated("permission", "allow", "{0} click {1}")),
            ("share_permitted", ["user", "token"], regulated("permission", "allow", "{0} share {1}")),
            ("submit_required", ["user", "query"],
             regulated("obligation", "deny", "{0} submit a proof of {1}", "submit_permitted")),
            ("submit_permitted", ["user", "query"], regulated("permission", "allow", "{0} submit a proof of {1}")),
            ("open_required", ["user", "desk"], regulated("obligation", "deny", "{0} open {1}", "open_permitted")),
            ("open_permitted", ["user", "desk"], regulated("permission", "allow", "{0} open {1}"))]:
        preds[name] = {"arguments": args, "description": name, "regulated": reg}
    constants = {"alice": "user", "check": "control", "token1": "token", "desk1": "desk", "atlas": "service",
                 "beacon": "service", "tom": "thing", "q1": "query"}
    block = {"task": task}
    if addressee:
        block["addressee"] = {"sort": addressee[0], "constant": addressee[1]}
    if definites:
        block["definites"] = definites
    return {"language": LANGUAGE, "spec_revision": REVISION, "speech_acts": block,
            "profiles": sorted(["norms@0", "relational-fol@0", "speech-acts@0", *extra_profiles]),
            "vocabulary": {"sorts": {s: {"description": s} for s in
                                     ["user", "control", "token", "desk", "service", "thing", "query"]},
                           "predicates": preds,
                           "constants": {c: {"sort": s, "description": c} for c, s in constants.items()}}}


def unit(uid, start, kind, content=None, meaning="specified"):
    u = {"id": uid, "span": [start, start + 1], "kind": kind, "meaning": meaning, "support": "none"}
    if content is not None:
        u["content"] = content
    return u


def command(force, act, args):
    return {"command": {"force": force, "act": act, "args": args}}


def polar(body):
    return {"question": {"mode": "polar", "body": body}}


def which(mode, body=("unary", "reviewed", ["var", 0])):
    return {"question": {"mode": mode, "sort": "service", "domain": ["atlas", "beacon"], "body": list(body)}}


def U(p, c):
    return ["unary", p, ["const", c]]


def all_f(xs):
    acc = ["top"]
    for x in xs:
        acc = ["and", acc, x]
    return acc


MODEL = {"complete": True,
         "domains": {"user": ["alice"], "control": ["check"], "token": ["token1"], "desk": ["desk1"],
                     "service": ["atlas", "beacon"], "thing": ["tom"], "query": ["q1"]},
         "constants": {c: c for c in ["alice", "check", "token1", "desk1", "atlas", "beacon", "tom", "q1"]},
         "relations": {p: [] for p in ["reviewed", "cat", "animal", "disabled", "done_click", "done_open",
                                       "done_submit"]}}


def model(**relations):
    m = copy.deepcopy(MODEL)
    m["relations"].update(relations)
    return m


def elaborate(env, doc):
    r = run1({"id": "e", "kind": "speech-elaborate", "environment": env, "document": doc})
    assert r["status"] == "ok", r
    return r


def certificate(env, premises, conclusion, env_id, max_steps=20000):
    """Untrusted search over Lean's regenerated list, bound to Lean's identities."""
    raw = copy.deepcopy(env)
    raw.pop("speech_acts")
    raw["profiles"] = [p for p in raw["profiles"] if p not in ("speech-acts@0", "norms@0")]
    for entry in raw["vocabulary"]["predicates"].values():
        entry.pop("regulated", None)
    decoder = _Decoder()
    found = prove_entailment(Environment(raw), [decoder.decode(a) for a in premises], decoder.decode(conclusion),
                             max_steps=max_steps)
    if found.certificate is None:
        return None
    domain = "ve-meaning-v0.2:" + ",".join(env["profiles"]) + "\n"
    cert = dict(found.certificate)
    cert["environment_id"] = env_id
    cert["premise_meaning_ids"] = [digest(domain, {"environment_id": env_id, "ast": a}) for a in premises]
    cert["conclusion_meaning_id"] = digest(domain, {"environment_id": env_id, "ast": conclusion})
    return cert


def answer(env, doc, question, **fields):
    return run1({"id": "a", "kind": "speech-answer", "environment": env, "document": doc, "question": question,
                 **fields})


def test_alpha_command_elaborates_to_an_equality_guarded_w1_rule(lean):
    doc = {"units": [unit("u1", 0, "instruction", command("require", "click_required", ["check"]))]}
    r = elaborate(F0(), doc)
    [c] = r["commands"]
    assert c["demand"] == {"name": "cmd-u1", "predicate": "click_required", "sign": True,
                           "guard": ["and", ["and", ["eq", ["var", 1], ["const", "alice"]],
                                             ["eq", ["var", 0], ["const", "check"]]], ["top"]],
                           "unless": [], "over": []}
    assert c["paraphrase"] == "In this task, you are required to click check."
    assert r["legend"][:2] == ["This document is task t1.", "In this task, you are alice."]
    # The regenerated premises entail the requirement; nothing entails that the act was done.
    assert certificate(F0(), r["premises"], ["binary", "click_required", ["const", "alice"], ["const", "check"]],
                       r["environment_id"]) is not None
    assert certificate(F0(), r["premises"], ["binary", "done_click", ["const", "alice"], ["const", "check"]],
                       r["environment_id"], max_steps=2000) is None


