HARMS = ["data_loss", "server_outage", "job_failure", "task_delay", "task_abandonment"]


def p2_record_case(rng, n, env, policy):
    names = [f"x{i}" for i in range(1, rng.randint(1, 3) + 1)] + ["nothing"]
    log = Log()
    seq = 0
    for a in names:
        for h in HARMS:
            stated = rng.choice(["might", "leads", "cannot", None])
            if stated:
                seq += 1
                log.add(seq, f"T{seq}", "statement", statement(a, h, stated))
    alts = [{"name": a, "label": a} for a in names[:-1]] + [{"name": "nothing", "label": "doing nothing",
                                                                "inaction": True}]
    dx = log.add(seq + 1, "DX", "decision", record(str(n), "the_agent", "the agent", policy, alts, [],
                                                   log.cite(*[e["id"] for e in log.entries])))
    return {"id": f"rec-{n}", "kind": "risk-decision", "environment": env,
            "document": {"norms": [agent_ops_rules()[1]]}, "decision": dx, "entries": log.entries[:-1]}


