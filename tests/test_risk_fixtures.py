def elaborate(env, norms, units=None):
    document = {"norms": norms} | ({"units": units} if units is not None else {})
    res = one({"id": "p", "kind": "risk-elaborate", "environment": env, "document": document})
    assert res["status"] == "ok", res
    return res


def risk_base_environment(env, elaborated):
    """The regenerated base environment the inner certificates bind (Run.lean `riskBaseEnvironmentJson`)."""
    base = deepcopy(env)
    for field in ("alternatives", "risk", "unit_schema", "units"):
        base.pop(field, None)
    base["profiles"] = [p for p in base["profiles"] if p not in ("alternatives@0", "risk@0", "norms@0")]
    vocab = base["vocabulary"]
    vocab["predicates"] = {n: p for n, p in vocab["predicates"].items() if "regulated" not in p}
    generated = elaborated["e_risk"]
    vocab["sorts"][generated["sort"]] = {"description": "severity class (risk@0)"}
    for p, sorts in generated["predicates"].items():
        vocab["predicates"][p] = {"arguments": sorts, "description": f"generated by risk@0: {p}"}
    for c in generated["classes"]:
        vocab["constants"][c] = {"sort": generated["sort"], "description": f"severity class {c}"}
    return base


def conflict_packages(env, norms, units=None):
    """One certificate per conflict target of the inlined policy, over W1's (empty) base background."""
    elaborated = elaborate(env, norms, units)
    base = Environment(risk_base_environment(env, elaborated))
    packages = {}
    for target in elaborated["conflict_targets"]:
        conclusion = _bind(Not(_Decoder().decode(target["ast"])), target["sorts"])
        proof = prove_entailment(base, (), conclusion, max_steps=10000)
        if proof.status == "Found":
            packages[target["target"]] = {"environment_id": elaborated["environment_id"],
                                          "document_hash": elaborated["document_hash"],
                                          "target": target["target"], "certificate": proof.certificate}
    return elaborated, packages


def closure(edges):
    pairs = {tuple(e) for e in edges}
    while True:
        extra = {(a, d) for a, b in pairs for c, d in pairs if b == c} - pairs
        if not extra:
            return sorted(pairs)
        pairs |= extra


def structure(env, *, choosers, available, might_cells, leads_cells, harms=None, extra_harms=(), facts=None):
    """A finite model over E_risk's base vocabulary (the witness form of `decodeWitnessModel`)."""
    vocab, alt, risk = env["vocabulary"], env["alternatives"], env["risk"]
    sev = risk["severity"]["sort"]
    classes = risk["severity"]["classes"]
    of_sort = lambda s: [c for c, d in vocab["constants"].items() if d["sort"] == s]  # noqa: E731
    actions = [a for a, _ in available]
    domains = {}
    for s in vocab["sorts"]:
        if s == alt["chooser"]:
            domains[s] = list(choosers) + of_sort(s)
        elif s == alt["action"]:
            domains[s] = actions
        elif s == alt["harm"]:
            domains[s] = (of_sort(s) if harms is None else list(harms)) + list(extra_harms)
        else:
            domains[s] = of_sort(s)
    domains[sev] = list(classes)
    relations = {p: [] for p, d in vocab["predicates"].items() if "regulated" not in d}
    relations.update({
        alt["available"]: [[a, r] for a, r in available],
        alt["leads_to"]: [list(c) for c in leads_cells],
        "risk__might_lead_to": [list(c) for c in might_cells],
        "risk__class": [list(p) for p in risk["harm_classes"]],
        "risk__more_severe": [list(p) for p in closure(risk["severity"]["more_severe"])],
    })
    if alt.get("inaction"):
        relations[alt["inaction"]] = [[a] for a, _ in available if a == "nothing" or a.startswith("nothing_")]
    for p, rows in (facts or {}).items():
        relations[p] = [list(r) for r in rows]
    constants = {c: c for c in classes} | {c: c for c in vocab["constants"]}
    return {"complete": True, "domains": domains, "constants": constants, "relations": relations}


def decision_model(env, res, chooser, alternatives, facts=None):
    """The decision model of a record (4.4, Record.lean `decisionData`), read from the route's regenerated tables:
    the record's chooser, its alternatives, the harm constants, the class constants, `available`, `inaction`,
    the regenerated `leads_to` and `risk__might_lead_to`, the class and order tables, and the record's facts."""
    model = structure(env, choosers=[chooser], available=[(a["name"], chooser) for a in alternatives],
                      might_cells=sorted(might(res)), leads_cells=sorted(leads(res)), facts=facts)
    model["relations"][env["alternatives"]["inaction"]] = [[a["name"]] for a in alternatives if a.get("inaction")]
    return model


def followable(env, norms, packages, model, chooser):
    return one({"id": "f", "kind": "risk-followable", "environment": env, "document": {"norms": norms},
                "packages": packages, "witness": {"model": model, "chooser": chooser}})


def asimov_record(env, norms, alternatives, sts, harms, *, chooser="R", facts=None):
    """A record of 8.1's `asimov-risk`: the robot `R` and `harms_human(h)` for every harm constant."""
    policy = policy_of(env, norms)
    log = Log()
    for seq, (a, h, stated) in enumerate(sts, start=1):
        log.add(seq, f"T{seq}", "statement", statement(a, h, stated, author="the Asimov case annotator"))
    if facts is None:
        facts = [{"predicate": "harms_human", "args": [h], "entry": "T1"} for h in harms]
    dx = log.add(100, "DX", "decision", record("x", chooser, "the robot", policy, alternatives, [],
                                               log.cite(*[f"T{i}" for i in range(1, len(sts) + 1)]), facts))
    return log, dx, decide(env, norms, log, dx, supplied=log.entries[:-1])


