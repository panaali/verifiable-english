def k37_units(form, harm):
    """The two rewrites of 2.3 with `r` D17's chooser. A base assertion unit cannot name the record-local chooser
    `build_agent` (it is not a constant of E, and k35(d) rejects a constant of that name), so each unit
    quantifies over the agent sort instead: in D17's decision model the agent domain is exactly {build_agent},
    so `∀r. φ(r)` there is φ(build_agent)."""
    avail = ["binary", "available", ["var", 0], ["var", 1]]
    mt = ["binary", "risk__might_lead_to", ["var", 0], ["const", harm]]
    if form == "every-not":  # ¬∃a. available(a, r) ∧ might(a, h)
        body = ["not", ["exists", "action", ["and", avail, mt]]]
    else:  # ∃a. available(a, r) ∧ ¬might(a, h)
        body = ["exists", "action", ["and", avail, ["not", mt]]]
    return [{"label": f"{form}-{harm}", "ast": ["forall", "agent", body]}]


