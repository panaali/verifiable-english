def test_k22b_strict_inclusion_rule_ps():
    harms = {"destruction": ("the robot's destruction", "severe"), "damage": ("the robot's damage", "minor")}
    env = asimov_risk(harms, classes=("severe", "minor"))
    rule_l = rule_("rule-l", ["not", ["unary", "lawful", ["var", 0]]])
    # PS: ∃r. available(a, r) ∧ ∃a′. available(a′, r) ∧ a′ ≠ a ∧ lawful(a′)
    #        ∧ (∀h. might(a′, h) → might(a, h)) ∧ (∃h. might(a, h) ∧ ¬might(a′, h))
    subset = ["forall", "harm", ["implies", ["binary", "risk__might_lead_to", ["var", 1], ["var", 0]],
                                 ["binary", "risk__might_lead_to", ["var", 3], ["var", 0]]]]
    strict = ["exists", "harm", ["and", ["binary", "risk__might_lead_to", ["var", 3], ["var", 0]],
                                 ["not", ["binary", "risk__might_lead_to", ["var", 1], ["var", 0]]]]]
    rule_ps = rule_("rule-ps", ["exists", "robot", ["and", ["binary", "available", ["var", 1], ["var", 0]],
                                ["exists", "action", ["and", ["and", ["and", ["and",
                                    ["binary", "available", ["var", 0], ["var", 1]],
                                    ["not", ["eq", ["var", 0], ["var", 2]]]],
                                    ["unary", "lawful", ["var", 0]]], subset], strict]]]])
    alts = [{"name": "fire", "label": "the fire rescue"}, {"name": "water", "label": "the water rescue"},
            {"name": "combined", "label": "the combined rescue"},
            {"name": "nothing", "label": "doing nothing", "inaction": True}]
    sts = [("fire", "destruction", "might"), ("fire", "damage", "cannot"), ("water", "damage", "might"),
           ("water", "destruction", "cannot"), ("nothing", "destruction", "cannot"), ("nothing", "damage", "cannot"),
           ("combined", "destruction", "might"), ("combined", "damage", "might")]
    facts = [{"predicate": "lawful", "args": [a], "entry": "T1"} for a in ("fire", "water", "combined")]
    _, _, res = asimov_record(env, [rule_l, rule_ps], alts, sts, harms, facts=facts)
    assert res["status"] == "ok", res
    s = statuses(res)
    assert s["combined"] == (False, False, [2])
    assert s["fire"][:2] == (True, True) and s["water"][:2] == (True, True)
    assert s["nothing"] == (False, False, [1])
    assert res["clear"] == ["fire", "water"]


