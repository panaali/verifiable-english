def test_k29_prevents_and_excludes_on_the_k21_record():
    """The words are evaluated here from the route's regenerated tables (`might`, `leads`) with the definitions
    of 2.2: prevents(a, h) = ¬leads_to(a, h) ∧ another available action leads to h; excludes(a, h) = ¬might(a, h)."""
    env = asimov_risk(A2)
    norms = [asimov_rules()[r] for r in ("1", "2x", "3")]
    _, _, res = asimov_record(env, norms, A2_ALTS, A2_STATEMENTS, A2)
    assert res["status"] == "ok", res
    names = [a["name"] for a in A2_ALTS]
    mt, lt = might(res), leads(res)

    def prevents(a, h):
        return (a, h) not in lt and any((b, h) in lt for b in names if b != a)

    def excludes(a, h):
        return (a, h) not in mt

    assert prevents("rescue_p", "p_death")
    assert not excludes("rescue_p", "p_death")
    assert excludes("rescue_q", "q_injury")


