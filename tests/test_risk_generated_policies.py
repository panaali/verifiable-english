"""risk@0 on 1,000 generated policies (docs/spec/risk.md 8.3, second item).

"The Lean `risk-elaborate` output round-trips through Python's dispatch, and its
certificates replay in Lean on 1,000 generated risk policies."

Each policy is 1 to 3 W1 norm objects on `permitted` and `required` over a small
risk environment without units (agent-ops with the W6 extension and the
quantity-kind fields removed). Guards are drawn from the risk words
(`risk__might_lead_to`, `risk__class`, `risk__or_worse`, `risk__less_worst`),
`leads_to` and alt's four profile words, under negation, conjunction and
disjunction, with random signs and occasional `over` precedence. For each
policy:

- `ve.risk.run_case` (Python's dispatch) returns the direct Lean output of
  `risk-elaborate`, byte for byte;
- every conflict target is searched by Python's `prove_entailment` over the
  regenerated base environment (built here as JSON equal to Lean's
  `riskBaseEnvironmentJson`), first with `Background_baseAlt ++ riskPremises`,
  then with no premises (the "or fewer" binding of 4.7), on a small budget;
- replaying the packages with `risk-conflict` gives CONFLICT-FREE exactly when
  every target has a certificate, so every certificate Python found is accepted;
- a tampered package (target renamed, or document hash changed) makes a
  CONFLICT-FREE replay UNKNOWN.

Lean calls are batched per shard.
"""
from __future__ import annotations

import json
import random
import subprocess
from copy import deepcopy
from functools import lru_cache
from pathlib import Path

import pytest

from conformance.risk import agent_ops, rule
from ve.ast import Not, _Decoder, formula_from_data
from ve.entailment import prove_entailment
from ve.environment import Environment
from ve.norms import _bind
from ve.risk import run_case

ROOT = Path(__file__).resolve().parents[1]
BIN = ROOT / "lean" / ".lake" / "build" / "bin" / "ve_risk_route"

pytestmark = pytest.mark.skipif(not BIN.exists(), reason="ve_risk_route is not built")

POLICIES = 1000
SHARDS = 10
SEED = 20260929
MAX_STEPS = 400


def run(cases):
    out = subprocess.run([str(BIN), "-"], input=json.dumps(cases), text=True, capture_output=True,
                         check=False, timeout=600)
    assert out.returncode in (0, 1), out.stderr
    rows = json.loads(out.stdout)
    assert len(rows) == len(cases)
    return rows


# ---------------------------------------------------------------------------- the environment

def environment():
    """agent-ops without units: no W6 extension, no quantity kinds, no required estimators."""
    env = agent_ops()
    del env["unit_schema"], env["units"]
    del env["risk"]["quantity_kinds"], env["risk"]["required_estimators"]
    return env


ENV = environment()
HARMS = sorted(ENV["vocabulary"]["constants"])
CLASSES = ENV["risk"]["severity"]["classes"]


def risk_base_environment(env):
    """Lean's `riskBaseEnvironmentJson` (lean/VE/Risk/Run.lean): the blocks, the W6 extension, the regulated
    predicates and `alternatives@0`, `risk@0`, `norms@0` removed; the severity sort, the three generated
    predicates and the class constants added with the descriptions written there."""
    base = deepcopy(env)
    for key in ("alternatives", "risk", "unit_schema", "units"):
        base.pop(key, None)
    base["profiles"] = [p for p in env["profiles"] if p not in ("alternatives@0", "risk@0", "norms@0")]
    vocabulary = base["vocabulary"]
    vocabulary["predicates"] = {name: p for name, p in vocabulary["predicates"].items() if "regulated" not in p}
    alt = env["alternatives"]
    sev = env["risk"]["severity"]["sort"]
    vocabulary["sorts"][sev] = {"description": "severity class (risk@0)"}
    for name, sorts in (("risk__might_lead_to", [alt["action"], alt["harm"]]), ("risk__class", [alt["harm"], sev]),
                        ("risk__more_severe", [sev, sev])):
        vocabulary["predicates"][name] = {"arguments": sorts, "description": f"generated by risk@0: {name}"}
    for c in env["risk"]["severity"]["classes"]:
        vocabulary["constants"][c] = {"sort": sev, "description": f"severity class {c}"}
    return base


@lru_cache(maxsize=1)
def base_environment():
    return Environment(risk_base_environment(ENV))


# ---------------------------------------------------------------------------- the generator

def _v(i):
    return ["var", i]


def _c(name):
    return ["const", name]


def atom(rng):
    """One guard atom in the rule context `[action]` (`var 0` is the action)."""
    h, c = rng.choice(HARMS), rng.choice(CLASSES)
    return rng.choice([
        lambda: ["binary", "risk__might_lead_to", _v(0), _c(h)],
        lambda: ["binary", "leads_to", _v(0), _c(h)],
        lambda: ["binary", "risk__class", _c(h), _c(c)],
        lambda: ["binary", "risk__or_worse", _c(h), _c(c)],
        lambda: ["exists", "harm", ["and", ["binary", "risk__class", _v(0), _c(c)],
                                    ["binary", "risk__might_lead_to", _v(1), _v(0)]]],
        lambda: ["exists", "harm", ["and", ["binary", "risk__or_worse", _v(0), _c(c)],
                                    ["binary", "risk__might_lead_to", _v(1), _v(0)]]],
        lambda: ["exists", "action", ["binary", "risk__less_worst", _v(0), _v(1)]],
        lambda: ["exists", "action", ["binary", "risk__less_worst", _v(1), _v(0)]],
        lambda: ["binary", "allows", _v(0), _c(h)],
        lambda: ["binary", "prevents", _v(0), _c(h)],
        lambda: ["exists", "agent", ["and", ["binary", "available", _v(1), _v(0)],
                                     ["binary", "avoidable", _c(h), _v(0)]]],
        lambda: ["exists", "agent", ["and", ["binary", "available", _v(1), _v(0)],
                                     ["binary", "unavoidable", _c(h), _v(0)]]],
    ])()


def guard(rng, depth=2):
    r = rng.random()
    if depth == 0 or r < 0.45:
        return atom(rng)
    if r < 0.65:
        return ["not", guard(rng, depth - 1)]
    return [rng.choice(["and", "and", "or"]), guard(rng, depth - 1), guard(rng, depth - 1)]


def policy(index):
    rng = random.Random(SEED * 10_000 + index)
    rules = [rule(f"r{k + 1}", rng.choice(["permitted", "required"]), rng.random() < 0.5, guard(rng))
             for k in range(rng.randint(1, 3))]
    for a in rules:
        for b in rules:
            A, B = a["norm"], b["norm"]
            if (A is not B and A["predicate"] == B["predicate"] and A["sign"] != B["sign"]
                    and not A["over"] and not B["over"] and rng.random() < 0.4):
                A["over"] = [B["name"]]
    return rules


def source(index):
    return {"id": f"g{index}", "environment": deepcopy(ENV), "document": {"norms": policy(index)}}


# ---------------------------------------------------------------------------- certificates

def packages_for(elaborated):
    """Python's certificates for the conflict targets it proves on the budget, as packages."""
    base = base_environment()
    full = [formula_from_data(base, p["ast"]) for p in elaborated["alternatives"] + elaborated["risk_premises"]]
    packages = {}
    for target in elaborated["conflict_targets"]:
        conclusion = _bind(Not(_Decoder().decode(target["ast"])), target["sorts"])
        for premises in (full, ()):
            proof = prove_entailment(base, premises, conclusion, max_steps=MAX_STEPS)
            if proof.status == "Found":
                packages[target["target"]] = {
                    "environment_id": elaborated["environment_id"], "document_hash": elaborated["document_hash"],
                    "target": target["target"], "certificate": proof.certificate}
                break
    return packages


def tampered(packages, index):
    changed = deepcopy(packages)
    name = sorted(changed)[index % len(changed)]
    if index % 2:
        changed[name]["target"] = name + "-renamed"
    else:
        changed[name]["document_hash"] = "0" * 64
    return changed


# ---------------------------------------------------------------------------- the suite

WORDS = ("risk__might_lead_to", "risk__class", "risk__or_worse", "risk__less_worst", "leads_to",
         "avoidable", "unavoidable", "allows", "prevents")


@pytest.mark.parametrize("shard", range(SHARDS))
def test_generated_policies_round_trip_and_replay(shard):
    indices = range(shard * POLICIES // SHARDS, (shard + 1) * POLICIES // SHARDS)
    sources = [source(i) for i in indices]
    direct = run([s | {"kind": "risk-elaborate"} for s in sources])

    # Python's dispatch returns the route's answer unchanged
    for s, d in zip(sources, direct):
        assert run_case(deepcopy(s) | {"kind": "risk-elaborate"}) == d, s["id"]
    assert all(d["status"] == "ok" for d in direct), [d for d in direct if d["status"] != "ok"][:3]

    found = [packages_for(d) for d in direct]
    complete = [set(p) == {t["target"] for t in d["conflict_targets"]} for d, p in zip(direct, found)]
    replays = [s | {"id": s["id"] + "-c", "kind": "risk-conflict", "packages": p} for s, p in zip(sources, found)]
    tampers = [s | {"id": s["id"] + "-t", "kind": "risk-conflict", "packages": tampered(p, i)}
               for i, (s, p, ok) in enumerate(zip(sources, found, complete)) if ok and p]
    results = run(replays + tampers)
    verdicts = [r["verdict"] for r in results[:len(replays)]]
    assert all(r["status"] == "ok" for r in results)
    # CONFLICT-FREE exactly when every target has a certificate: every certificate found is accepted
    assert [v == "CONFLICT-FREE" for v in verdicts] == complete, [
        (s["id"], v, sorted(p)) for s, v, p, ok in zip(sources, verdicts, found, complete)
        if (v == "CONFLICT-FREE") != ok]
    assert [r["verdict"] for r in results[len(replays):]] == ["UNKNOWN"] * len(tampers)

    # the shard is not vacuous: every word and `over` occur, most targets are proved, some policies stay UNKNOWN
    text = json.dumps([s["document"] for s in sources])
    assert all(f'"{w}"' in text for w in WORDS)
    assert any(r["norm"]["over"] for s in sources for r in s["document"]["norms"])
    targets = sum(len(d["conflict_targets"]) for d in direct)
    assert sum(len(p) for p in found) > targets // 2
    assert 0 < sum(complete) < len(sources)


def test_base_environment_binding_is_checked():
    """The base environment built here is Lean's: a certificate over it is accepted, and the same proof over an
    environment differing only in one generated description is rejected (the binding is checked)."""
    s = source(0)
    s["document"]["norms"] = [rule("x1", "permitted", False, ["binary", "risk__might_lead_to", _v(0), _c("data_loss")]),
                              rule("x2", "permitted", True,
                                   ["not", ["binary", "risk__might_lead_to", _v(0), _c("data_loss")]])]
    elaborated = run([s | {"kind": "risk-elaborate"}])[0]
    packages = packages_for(elaborated)
    assert sorted(packages) == sorted(t["target"] for t in elaborated["conflict_targets"])
    other = risk_base_environment(ENV)
    other["vocabulary"]["sorts"]["severity"]["description"] = "severity"
    other_env = Environment(other)
    assert other_env.environment_id != base_environment().environment_id
    stale = deepcopy(packages)
    for name, package in stale.items():
        target = next(t for t in elaborated["conflict_targets"] if t["target"] == name)
        conclusion = _bind(Not(_Decoder().decode(target["ast"])), target["sorts"])
        proof = prove_entailment(other_env, (), conclusion, max_steps=MAX_STEPS)
        assert proof.status == "Found"
        package["certificate"] = proof.certificate
    good, bad = run([s | {"id": "good", "kind": "risk-conflict", "packages": packages},
                     s | {"id": "bad", "kind": "risk-conflict", "packages": stale}])
    assert good["verdict"] == "CONFLICT-FREE", good
    assert bad["verdict"] == "UNKNOWN", bad
