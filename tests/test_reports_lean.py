def prover_env(env, r):
    """The untrusted prover's copy of E_reports: the reports block and profile removed, the generated
    predicates declared as ordinary ones."""
    raw = copy.deepcopy(env)
    raw["vocabulary"].pop("reports", None)
    raw["profiles"] = [p for p in raw["profiles"] if p != "reports@0"]
    for entry in raw["vocabulary"]["constants"].values():
        entry.pop("verbalisation", None)
    for k in r["keys"]:
        raw["vocabulary"]["predicates"][k["name"]] = {"arguments": k["arguments"], "description": k["name"]}
    return raw


def certificate(env, r, checked, conclusion, env_id, profiles=PROFILES, max_steps=20000):
    """Untrusted search over Lean's regenerated list, bound to Lean's identities."""
    decoder = _Decoder()
    found = prove_entailment(Environment(prover_env(env, r)), [decoder.decode(a) for a in checked],
                             decoder.decode(conclusion), max_steps=max_steps)
    if found.certificate is None:
        return None
    domain = "ve-meaning-v0.2:" + ",".join(profiles) + "\n"
    cert = dict(found.certificate)
    cert["environment_id"] = env_id
    cert["premise_meaning_ids"] = [digest(domain, {"environment_id": env_id, "ast": a}) for a in checked]
    cert["conclusion_meaning_id"] = digest(domain, {"environment_id": env_id, "ast": conclusion})
    return cert


def route_certificate(d, gamma, conclusion, env=None, cert_from=None, envelope_from=None, max_steps=20000):
    """reports-certificate over `literals ++ Γ_reports ++ Γ` (E₀ has no literals)."""
    env = env or E0()
    r = elaborate(d, env)
    src = cert_from or r
    cert = certificate(env, src, premises(src) + gamma, conclusion, src["environment_reports_id"],
                       max_steps=max_steps)
    if cert is None:
        return None, r
    envelope = (envelope_from or src)["envelope"]
    out = run1({"id": "c", "kind": "reports-certificate", "environment": env, "document": d,
                "premises": gamma, "conclusion": conclusion, "certificate": cert, "envelope": envelope})
    assert out["status"] == "ok", out
    return out, r


