def report(holder, act, context, content, literal=None):
    r = {"holder": holder, "act": act, "context": context, "content": content}
    if literal is not None:
        r["literal"] = literal
    return {"report": r}


def assess(judgment, content, record="a1"):
    return {"assessment": {"judgment": judgment, "record": record, "content": content}}


def neg(x):
    return {"negated": x}


def kind_of(content):
    if "negated" in content:
        return kind_of(content["negated"])
    if "report" in content:
        r = content["report"]
        return ["attributed", r["holder"], r["act"], kind_of(r["content"])]
    if "assessment" in content:
        a = content["assessment"]
        return ["hedged", "could" if a["judgment"] == "may" else "likely", kind_of(a["content"])]
    return "asserted"


def unit(uid, start, content):
    return {"id": uid, "span": [start, start + 1], "kind": kind_of(content), "content": content,
            "meaning": "specified", "support": "testimony"}


def assessment_nodes(content):
    tag, value = next(iter(content.items()))
    if tag == "negated":
        return assessment_nodes(value)
    if tag == "report":
        return assessment_nodes(value["content"])
    if tag == "assessment":
        return [value] + assessment_nodes(value["content"])
    return []


def doc(*contents, **extra):
    """3.3: a unit whose tree has an assessment node is `open`, listing generated names;
    listing every generated assessment name of the document covers its own."""
    d = {"units": [unit(f"u{i + 1}", 2 * i, c) for i, c in enumerate(contents)], "contexts": CONTEXTS,
         "assessments": [A1]}
    d.update(extra)
    keys = {(n["judgment"], n["record"], json.dumps(n["content"], sort_keys=True))
            for u in d["units"] for n in assessment_nodes(u["content"])}
    generated = [f"reports__{j}__{k}" for j in ("may", "probably")
                 for k in range(1, 1 + sum(key[0] == j for key in keys))]
    for u in d["units"]:
        if assessment_nodes(u["content"]):
            u["meaning"] = {"open": generated}
    return d


def elaborate(d, env=None):
    r = run1({"id": "e", "kind": "reports-elaborate", "environment": env or E0(), "document": d})
    assert r["status"] == "ok", r
    return r


def names(r):
    return {k["name"]: k for k in r["keys"]}


def premises(r):
    return [p["ast"] for p in r["premises"]]


