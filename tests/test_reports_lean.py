def test_beta_not_closed_and_scoped_consequence(lean):
    implies = ["implies", U("reviewed", "service"), U("safe", "service")]
    inner = report("anthropic", "believes", "c1", ast(U("safe", "service")))
    d = doc(report("anthropic", "believes", "c1", ast(U("reviewed", "service"))),
            report("anthropic", "believes", "c1", ast(implies)),
            report("the_article", "says", "c3", inner),
            scoped=[{"id": "s1", "payloads": ["u1", "u2"], "conclusion": ast(U("safe", "service"))}])
    r = elaborate(d)
    keys = names(r)
    believes = [n for n in keys if n.startswith("reports__believes__")]
    assert len(believes) == 3 and len(r["premises"]) == 3  # the belief-in-safe key exists, no premise mentions it
    premised = {p["ast"][1] for p in r["premises"]}
    [safe_key] = [n for n in believes if n not in premised]
    assert certificate(E0(), r, premises(r), U(safe_key, "anthropic"), r["environment_reports_id"],
                       max_steps=2000) is None
    env_id = r["envelope"]["environment_id"]
    cert = certificate(E0(), {"keys": []}, [U("reviewed", "service"), implies], U("safe", "service"), env_id)
    out = run1({"id": "s", "kind": "reports-scoped", "environment": E0(), "document": d,
                "certificates": {"s1": cert}})
    assert out["scoped"] == [{"id": "s1", "environment_id": env_id, "background": 0, "status": "FOLLOWS"}]
    # scoped_not_premise: the same document without s1 regenerates the same E_reports and premises.
    d0 = copy.deepcopy(d)
    del d0["scoped"]
    r0 = elaborate(d0)
    assert r0["environment_reports_id"] == r["environment_reports_id"] and r0["premises"] == r["premises"]


