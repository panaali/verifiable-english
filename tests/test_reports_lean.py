def test_phi_identity_envelope(lean):
    alpha = doc(report("the_article", "says", "c3", ast(U("safe", "service"))))
    out, r = route_certificate(alpha, [], U("reports__says__1", "the_article"))
    assert out["valid"] is True
    # c3's tense changed: E_reports and Γ_reports byte-identical, only the envelope differs.
    changed = copy.deepcopy(alpha)
    changed["contexts"][2]["tense"] = "past"
    out2, r2 = route_certificate(changed, [], U("reports__says__1", "the_article"), cert_from=r, envelope_from=r)
    assert r2["environment_reports_id"] == r["environment_reports_id"] and premises(r2) == premises(r)
    assert out2["bindings"] == {"inner": True, "envelope": False} and out2["valid"] is False
    # safe replaced by reviewed (the sole key's payload): likewise.
    payload = doc(report("the_article", "says", "c3", ast(U("reviewed", "service"))))
    out3, r3 = route_certificate(payload, [], U("reports__says__1", "the_article"), cert_from=r, envelope_from=r)
    assert r3["envelope"]["document_id"] != r["envelope"]["document_id"]
    assert out3["bindings"]["envelope"] is False and out3["valid"] is False
    # A literal added and the holder changed alter the document id too.
    for variant in [doc(report("the_article", "says", "c3", ast(U("safe", "service")), literal="the service is safe")),
                    doc(report("anthropic", "says", "c3", ast(U("safe", "service"))))]:
        assert elaborate(variant)["envelope"]["document_id"] != r["envelope"]["document_id"]


