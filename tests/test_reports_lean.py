def E0(profiles=PROFILES, block=True, verbalise=None):
    """E₀ of 10.1, with the sort `service` renamed `system`: P0's vocabulary decoder rejects a sort and a
    constant of one name (`duplicate declaration`), and 10.1 declares `service : service`."""
    sorts = ["organisation", "text", "system", "model", "evidence"]
    preds = {"safe": ["system"], "helpful": ["model"], "was_helpful": ["model"], "human": ["model"],
             "reviewed": ["system"], "publishes": ["organisation", "system"]}
    constants = {"anthropic": "organisation", "the_article": "text", "the_team": "organisation",
                 "service": "system", "claude": "model", "e1": "evidence"}
    vocab = {"sorts": {s: {"description": s} for s in sorts},
             "predicates": {p: {"arguments": a, "description": p} for p, a in preds.items()},
             "constants": {c: {"sort": s, "description": c} for c, s in constants.items()}}
    if verbalise:
        name, words = verbalise
        vocab["constants"][name] = {"sort": "organisation", "description": name, "verbalisation": words}
    if block:
        vocab["reports"] = {"holders": ["organisation", "text"], "evidence": "evidence"}
    return {"language": LANGUAGE, "profiles": sorted(profiles), "spec_revision": REVISION, "vocabulary": vocab}


