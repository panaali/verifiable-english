"""Print the six-example report, including the byte-identical five-view legend.

Run from the repository root with:
UV_CACHE_DIR=/private/tmp/ve-uv-cache-fluent uv run --frozen python examples/fluent_views.py
"""
from pathlib import Path

from ve import Environment, parse, render, render_vocabulary
from ve.printer import VIEWS


def report():
    directory = Path(__file__).parent / "fluent"
    env = Environment.from_json((directory / "environment.json").read_bytes())
    document = parse(env, (directory / "examples.ve").read_bytes())
    legends = {render_vocabulary(env, view) for view in VIEWS}
    assert len(legends) == 1
    legend = legends.pop()
    surfaces = {view: render(document, env, view).splitlines() for view in VIEWS}
    labels = ["Guarded review", "Dependent owner", "One owner for all services",
              "No unreviewed deployed service", "Exception and negative ownership", "Owner equality"]
    assert len(document.formulas) == len(labels) == 6
    parts = [
        "# Six examples across all five views\n\n",
        "Generated by `examples/fluent_views.py` from the committed environment and strict source\n",
        "in `examples/fluent/`. These are the six statements of one document; fluent names\n",
        "are unique across statements. All five cells show the identical legend below.\n",
    ]
    for index, label in enumerate(labels):
        parts.append(f"\n## {index + 1}. {label}\n\n```text\n")
        for view in VIEWS:
            parts.append(f"{view}: {surfaces[view][index]}\n")
        parts.append("```\n")
    parts.extend(["\n## Shared vocabulary legend\n\n```json\n", legend, "```\n"])
    return "".join(parts)


if __name__ == "__main__":
    print(report(), end="")
