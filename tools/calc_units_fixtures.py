"""Write or check `lean/VE/Calc/UnitsExamples.lean`, the Lean `#guard`s of the `ve-units@2` fixture table.

    python tools/calc_units_fixtures.py --write
    python tools/calc_units_fixtures.py --check

The table is `tests/calc_units_fixtures.py` (math-evidence spec 6.2). For each fixture the file holds a `#guard`
that Lean's answer is the table's, so `lake build` evaluates every fixture and `tools/trust_mutants.py` reads them as
the checks of `VE.Calc.Units`; `tests/test_calc_units.py` prints the same answers per fixture. `--check` fails when
the file differs from its rendering.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

TARGET = ROOT / "lean/VE/Calc/UnitsExamples.lean"

HEADER = '''import VE.Calc.Units

/-! The `ve-units@2` fixtures (`tests/calc_units_fixtures.py`, math-evidence spec 6.2) as `#guard`s.
Generated by `python3 tools/calc_units_fixtures.py --write`; do not edit. Each guard compares an answer of
`VE.Calc.Units` (a decoded environment, a dimension in words, a claim's checks, an identity) with the table's. -/

namespace VE.Calc.UnitsExamples
open Lean VE.Calc VE.Calc.Units VE.Numbers

def says {α : Type} (r : Except String α) (f : α → String) : String :=
  match r with | .ok a => "ok " ++ f a | .error e => e
def env! (s : String) : UnitEnv :=
  match Json.parse s >>= decode with | .ok u => u | .error e => ⟨[], .str e⟩
def dims (s : String) (vals : List (String × Option String)) (e : Expr) : String :=
  says (do let Γ ← (env! s).context vals; dimE Γ e) dimWords
/-- A claim's checks; `the displacement` are the rounded expression's words. -/
def check (s : String) (vals : List (String × Option String)) (c : Claim) : String :=
  says (do let u := env! s; let Γ ← u.context vals; checkClaim u Γ "the displacement" c) fun _ => "admitted"
/-- Lengths times 1,000 and times 2. -/
def ρ : Rescale := ⟨fun b => if b = "length" then 1000 else if b = "time" then 2 else 1, fun b => by
  by_cases h : b = "length" <;> by_cases h' : b = "time" <;> simp only [h, h', if_true, if_false] <;> decide⟩
instance : DecidablePred PhysDim.Normal := fun d => by unfold PhysDim.Normal; infer_instance
def context! (s : String) (vals : List (String × Option String)) : String → Option PhysDim :=
  match (env! s).context vals with | .ok Γ => Γ | .error _ => fun _ => none
/-- Each claim decided under the values and units, then again in the units `ρ`. -/
def rescaled (s : String) (vals : List (String × Option String)) (σ : Values) (c : Claim) : String :=
  let u := env! s
  let τ : Values := fun n => (σ n).orElse fun _ => u.values n
  let word := fun (v : Verdict) => match v with | .holds => "holds" | .fails => "fails" | .undefined => "undefined"
  says (u.context vals) fun Γ => word (c.decide τ) ++ " " ++ word (c.decide (ρ.apply Γ τ))
def decoded (s : String) : String := says (Json.parse s >>= decode) fun u => reprStr (u.units.map (·.name))
/-- 10,000 nested lists. -/
def deep : String := String.mk (List.replicate 10000 '[' ++ List.replicate 10000 ']')
'''


def render() -> str:
    from tests import calc_units_fixtures as F
    lines = [HEADER]
    for name, kind, term in F.DEFINITIONS:
        lines.append(f"def {name} : {kind} :=\n  {term}")
    lines.append("")
    for key, expression, expected in F.FIXTURES + F.MALFORMED:
        lines.append(f"-- {key}")
        lines.append(f"#guard ({expression}) ==\n  {json.dumps(expected, ensure_ascii=False)}")
    lines.append("\nend VE.Calc.UnitsExamples\n")
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        TARGET.write_text(text)
        return 0
    if not TARGET.exists() or TARGET.read_text() != text:
        print(f"{TARGET.relative_to(ROOT)} differs from the fixture table; run --write")
        return 1
    print("PASS: the Lean fixture guards are the fixture table")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
