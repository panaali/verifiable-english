"""Generate or check the senses lock (docs/spec/senses-PLAN.md 2.7, D17): `ve/senses/LOCK.json` holds
`senses_version` and the SHA-256 of each senses definition file, and `lean/VE/Senses/Version.lean` holds the
version as Lean's `sensesVersion`. A hash that changes needs a new `senses_version`; the pre-commit hook checks
the staged files against HEAD's lock (`tools/hooks/precommit.py`). The senses files are not in
`ve/english_grammar/LOCK.json`, so a senses change leaves `actions_version` alone (D10).

    python tools/senses_lock.py                             # check
    python tools/senses_lock.py --write [--senses-version V]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCK = "ve/senses/LOCK.json"
LOCK_FORMAT = "ve.senses-lock@1"
VERSION_TARGET = "lean/VE/Senses/Version.lean"
HASHED = tuple(f"lean/VE/Senses/{name}.lean" for name in
               ("Assignment", "Decode", "Dictionary", "Preamble", "Project", "Read"))
VERSION = re.compile(r"[1-9][0-9]{0,8}")
Read = Callable[[str], "bytes | None"]


def render_version(version: str) -> bytes:
    return ("/-! Generated by `python tools/senses_lock.py --write` from `ve/senses/LOCK.json`; do not edit. -/\n"
            "namespace VE.Senses\n\n"
            "/-- The version of the senses definitions (plan 2.7, D17): raised on every change to a file\n"
            "`ve/senses/LOCK.json` hashes. -/\n"
            f'def sensesVersion : String := "{version}"\n\nend VE.Senses\n').encode()


def render_lock(version: str, hashes: dict[str, str]) -> bytes:
    return (json.dumps({"format": LOCK_FORMAT, "senses_version": version, "files": dict(sorted(hashes.items()))},
                       indent=1) + "\n").encode()


def parse_lock(blob: bytes) -> dict:
    lock = json.loads(blob)
    if type(lock) is not dict or set(lock) != {"format", "senses_version", "files"} \
            or lock["format"] != LOCK_FORMAT or type(lock["senses_version"]) is not str \
            or not VERSION.fullmatch(lock["senses_version"]) or type(lock["files"]) is not dict:
        raise ValueError(f"{LOCK}: fields are format {LOCK_FORMAT}, senses_version (a number) and files")
    return lock


def check(read: Read, base_lock: bytes | None = None) -> list[str]:
    """Every fault of the lock as messages: the version module, each recorded hash, and against the base lock a
    changed hash with `senses_version` unchanged."""
    blob = read(LOCK)
    if blob is None:
        return [f"{LOCK}: missing; run tools/senses_lock.py --write --senses-version V"]
    try:
        lock = parse_lock(blob)
    except ValueError as exc:
        return [str(exc)]
    errors = []
    if read(VERSION_TARGET) != render_version(lock["senses_version"]):
        errors.append(f"{VERSION_TARGET}: does not hold senses_version {lock['senses_version']!r}; run --write")
    if sorted(lock["files"]) != sorted(HASHED):
        errors.append(f"{LOCK}: hashes {sorted(lock['files'])}, expected {sorted(HASHED)}; run --write")
    now = {path: None if read(path) is None else hashlib.sha256(read(path)).hexdigest() for path in HASHED}
    for path, digest in now.items():
        if digest is None:
            errors.append(f"{path}: hashed by {LOCK} but missing")
        elif lock["files"].get(path) not in (None, digest):
            errors.append(f"{path}: SHA-256 {lock['files'][path]} in {LOCK}, {digest} now; raise senses_version "
                          "and run --write")
    if base_lock is not None:
        base = parse_lock(base_lock)
        if base["senses_version"] == lock["senses_version"]:
            errors += [f"{path}: SHA-256 {base['files'].get(path)} at the base, {now[path]} now, with senses_version "
                       f"{lock['senses_version']!r} unchanged; raise it"
                       for path in HASHED if base["files"].get(path) != now[path]]
    return errors


def write(root: Path, version: str | None = None) -> list[str]:
    """Write the lock and the version module; the paths written. A changed hash needs a new version."""
    old = parse_lock((root / LOCK).read_bytes()) if (root / LOCK).is_file() else None
    if version is None and old is None:
        raise SystemExit(f"{LOCK} does not exist yet: give --senses-version")
    if version is not None and not VERSION.fullmatch(version):
        raise SystemExit(f"senses_version {version!r} is not a number")
    hashes = {path: hashlib.sha256((root / path).read_bytes()).hexdigest() for path in HASHED}
    version = version or old["senses_version"]
    if old is not None and hashes != old["files"] and version == old["senses_version"]:
        raise SystemExit(f"a hashed senses file changed: give a new --senses-version (now {version!r})")
    written = []
    for path, blob in ((VERSION_TARGET, render_version(version)), (LOCK, render_lock(version, hashes))):
        target = root / path
        if not target.is_file() or target.read_bytes() != blob:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(blob)
            written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--senses-version")
    args = parser.parse_args(argv)
    if args.write:
        for path in write(ROOT, args.senses_version):
            print(f"wrote {path}")
        return 0
    errors = check(lambda path: (ROOT / path).read_bytes() if (ROOT / path).is_file() else None)
    for error in errors:
        print(error, file=sys.stderr)
    if not errors:
        print(f"PASS: {LOCK} holds senses_version and the hash of each senses definition file")
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
