def sources(root: Path = ROOT) -> list[Path]:
    """Every Lean file of the tree (`lean/`, build output excluded)."""
    lean = root / "lean"
    return [p for p in sorted(lean.rglob("*.lean")) if ".lake" not in p.relative_to(lean).parts]


def module_name(key: str) -> str:
    """The Lean module of a file given by its path under `lean/` (`VE/Demo.lean` is `VE.Demo`)."""
    return key.removesuffix(".lean").replace("/", ".")


def tree_modules(root: Path = ROOT) -> list[str]:
    return [module_name(p.relative_to(root / "lean").as_posix()) for p in sources(root)]


def run_lean(root: Path, folder: Path, script: str, label: str, env: dict[str, str]) -> str:
    path = folder / f"{label}.lean"
    path.write_text(script)
    done = subprocess.run(["lake", "env", "lean", str(path)], cwd=root / "lean", text=True, capture_output=True,
                          check=False, env={**os.environ, **env})
    if done.returncode:
        raise SystemExit(f"lake env lean failed on {label} ({done.returncode}):\n{done.stderr}{done.stdout[-2000:]}")
    return done.stdout


def source_hash(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


# The train-only files' copies (module docstring; DESIGN.md section 4, step 2).
OVERLAY = ".lake/ve-inventory"  # under lean/
SWITCH = "VE_INVENTORY"         # "overlay": `inventory_target` is the overlay copy; unset or "committed": the committed


class StaleInventory(Exception):
    """No copy of a train-only file describes the tree: `changed` names the modules that differ."""

    def __init__(self, name: str, changed: list[str], command: str) -> None:
        self.name, self.changed = name, changed
        more = f", and {len(changed) - 5} more" if len(changed) > 5 else ""
        super().__init__(f"{name} is stale: {len(changed)} modules differ from the sources it was compiled from "
                         f"({', '.join(changed[:5])}{more}), and no fresh overlay copy describes them; rerun {command}")


def _train_entry(name: str) -> "regen_generated.Generated":
    entry = regen_generated.owner(name)
    if entry is None or entry.writer != "train" or name not in entry.paths:
        raise ValueError(f"{name} is not a train-only file (tools/regen_generated.py: writer=\"train\")")
    return entry


def _describes_lean(entry: "regen_generated.Generated") -> bool:
    """Whether the entry's files describe the Lean tree's modules (the lists, the manifests and their record), so
    that the committed declaration list records what its committed copy was compiled from."""
    return any(path == DECLARATIONS or path.removeprefix("lean/") in audit.MANIFESTS for path in entry.paths)


def lean_inputs(root: Path = ROOT) -> dict[str, str]:
    """What the Lean inventories are generated from: the SHA-256 of every module of the tree but the audit
    manifests (their outputs)."""
    outputs = {module_name(manifest) for manifest in audit.MANIFESTS}
    named = {module_name(p.relative_to(root / "lean").as_posix()): p for p in sources(root)}
    return {module: source_hash(path) for module, path in named.items() if module not in outputs}


def _inputs(entry: "regen_generated.Generated", root: Path) -> dict[str, str]:
    """What an overlay copy of the entry must have been generated from to describe the tree: the modules for the
    Lean inventories; for the others (pins, the assurance doc) the committed copies it rewrote, so a merge that
    changes them leaves the overlay stale (their own checks decide the rest: a pin is a build's, a doc renders)."""
    if _describes_lean(entry):
        return lean_inputs(root)
    return {path: source_hash(root / path) if (root / path).is_file() else "" for path in entry.paths}


def _stamp_path(entry: "regen_generated.Generated", root: Path) -> Path:
    return root / "lean" / OVERLAY / f"{entry.name}.stamp.json"


def overlay_copy(name: str, root: Path = ROOT) -> Path:
    return root / "lean" / OVERLAY / name


def inventory_status(name: str, root: Path = ROOT) -> tuple[Path, list[str]]:
    """The copy of the train-only file `name` (a repository path) that describes the tree at `root`, with [];
    or, when none does, the committed copy with the modules that differ. The overlay copy describes it when
    every file of its entry is in the overlay as its stamp records it, and the stamp's inputs are the tree's.
    The committed copy describes it when no module the entry covers differs from the committed declaration
    list's record (an entry that covers no module: always; its own check decides). So a module the branch
    changed, with no fresh overlay, is never read from the committed copy: it is named here."""
    entry, current = _train_entry(name), None
    try:
        stamp = json.loads(_stamp_path(entry, root).read_text())  # no stamp: no overlay, and nothing else is read
        files, current = stamp["files"], _inputs(entry, root)
        fresh = stamp["inputs"] == current and all(
            isinstance(files.get(path), str) and overlay_copy(path, root).is_file()
            and source_hash(overlay_copy(path, root)) == files[path] for path in entry.paths)
    except (OSError, ValueError, KeyError, TypeError, AttributeError):
        fresh = False
    if fresh:
        return overlay_copy(name, root), []
    if not _describes_lean(entry):
        return root / name, []
    outputs, current = {module_name(manifest) for manifest in audit.MANIFESTS}, current or _inputs(entry, root)
    try:
        recorded = {m: h for m, h in declaration_list(root / DECLARATIONS)[1].items() if m not in outputs}
    except (OSError, ValueError):
        recorded = {}
    return root / name, sorted(m for m in current.keys() | recorded.keys() if current.get(m) != recorded.get(m))


def inventory_path(name: str, root: Path = ROOT) -> Path:
    """The copy of the train-only file `name` that describes the tree (`inventory_status`); StaleInventory,
    naming the modules, when none does: never a fallback to a committed copy of another tree."""
    path, changed = inventory_status(name, root)
    if changed:
        raise StaleInventory(name, changed, " ".join("python3" if part == regen_generated.PY else part
                                                     for part in _train_entry(name).write[0]))
    return path


def inventory_target(name: str, root: Path = ROOT) -> Path:
    """Where a writer writes the train-only file `name`: the committed path, or with VE_INVENTORY=overlay the
    overlay copy. Any other value is an error, never a guess."""
    _train_entry(name)
    switch = os.environ.get(SWITCH, "")
    if switch not in ("", "committed", "overlay"):
        raise SystemExit(f"{SWITCH}={switch!r}: expected 'overlay' or 'committed'")
    return overlay_copy(name, root) if switch == "overlay" else root / name


def write_inventory(name: str, text: str, root: Path = ROOT, inputs: dict[str, str] | None = None) -> Path:
    """Write `text` as the train-only file `name` at `inventory_target`. An overlay copy is stamped with the
    entry's inputs: `inputs`, what the text was generated from, must still be the tree's. A stamp of other
    inputs starts over, so the entry is fresh only once each of its files is written from the same tree."""
    entry, target = _train_entry(name), inventory_target(name, root)
    target.parent.mkdir(parents=True, exist_ok=True)
    if target != root / name:
        current = _inputs(entry, root)
        if inputs is not None and inputs != current:
            raise SystemExit(f"{name}: a source changed while it was generated; rerun")
        try:
            stamp = json.loads(_stamp_path(entry, root).read_text())
            if stamp["inputs"] != current or not isinstance(stamp["files"], dict):
                raise ValueError
        except (OSError, ValueError, KeyError, TypeError):
            stamp = {"inputs": current, "files": {}}
        target.write_bytes(text.encode())
        stamp["files"][name] = hashlib.sha256(text.encode()).hexdigest()
        _stamp_path(entry, root).write_text(json.dumps(stamp, indent=1, sort_keys=True) + "\n")
    else:
        target.write_bytes(text.encode())
    return target


def dump_all(root: Path = ROOT, cache: bool = False) -> tuple[str, str, str]:
    """The statement dump, the predicate list and the declaration list over every module of the
    tree (each built first: a file no target imports has no object file until it is named). One
    Lean run imports `VE`; each module outside it is read by its own run, in parallel. The
    statements are those of the theorems of `lean/VE/Audit.lean` as `lean/audit.py --write`
    generates it from this declaration list, read by runs that import `VE`, one per part
    (`print_statements`); each audit
    manifest's hash is that of its generated text, so the list is current once the manifests are.
    With `cache` (the command line's), a dump of the same inputs that an earlier run stored is
    replayed instead (`tools/lean_dump_cache.py`)."""
    if cache:
        return tuple(lean_dump_cache.cached(lean_dump_cache.STATEMENTS, root, lambda: sources(root),
                                            lambda: list(dump_all(root)), count=3))
    all_modules = tree_modules(root)
    manifests = {module_name(path) for path in audit.MANIFESTS}
    modules = [module for module in all_modules if module not in manifests]
    built = subprocess.run(["lake", "build", *modules], cwd=root / "lean", text=True, capture_output=True,
                           check=False)
    if built.returncode:
        raise SystemExit(f"lake build of the tree's modules failed ({built.returncode}):\n"
                         f"{built.stderr}{built.stdout[-2000:]}")
    hashes = {module_name(p.relative_to(root / "lean").as_posix()): source_hash(p) for p in sources(root)}
    with tempfile.TemporaryDirectory(prefix="ve-statements-") as name:
        folder = Path(name)
        (folder / "modules.txt").write_text("\n".join(modules) + "\n")
        rest = run_lean(root, folder, TREE, "Tree", {"VE_TREE_MODULES": str(folder / "modules.txt")})
        outside = [line.removeprefix("outside ") for line in rest.splitlines() if line.startswith("outside ")]
        with ThreadPoolExecutor(max_workers=min(8, os.cpu_count() or 1)) as pool:
            alone = list(pool.map(lambda m: run_lean(root, folder, f"import Lean\nimport {m}\n" + ALONE,
                                                     f"Alone{outside.index(m)}", {"VE_PREDICATE_MODULE": m}),
                                  outside))
        lines = [line for text in (rest, *alone) for line in text.splitlines()]
        declared: dict[str, list[str]] = {}
        pending: list[str] = []
        for line in lines:
            if line.startswith("declaration "):
                pending.append(line.removeprefix("declaration "))
            elif line.startswith("generated "):
                pending.append(line)
            elif line.startswith("module "):
                declared[line.removeprefix("module ")], pending = pending, []
        try:
            manifest_theorems = audit.manifest_theorems({m: declared_constants(m, declared.get(m, [])) for m in modules})
        except (ValueError, AssertionError) as error:
            raise SystemExit(f"the declaration dump cannot give the audit manifests: {error}")
        names = sorted(manifest_theorems[audit.MANIFESTS[0]])
        theorem_imports = sorted(set(manifest_theorems[audit.MANIFESTS[0]].values()) & set(outside))
        theorems = print_statements(root, folder, names, statement_count(), theorem_imports)
    entries = parse(theorems)
    if sorted(entries) != names:
        missing = sorted(set(names) - set(entries))[:10]
        raise SystemExit(f"the dump lists {len(entries)} theorems, the audit {len(names)}; missing {missing}")
    scanned = sorted(line.removeprefix("module ") for line in lines if line.startswith("module "))
    if scanned != sorted(modules):
        raise SystemExit(f"the predicate scan read {len(scanned)} modules of the tree's {len(modules)}: "
                         f"missing {sorted(set(modules) - set(scanned))[:10]}")
    predicates = sorted(line.removeprefix("predicate ") for line in lines if line.startswith("predicate "))
    if hashes != {m: source_hash(p) for m, p in zip(all_modules, sources(root))}:
        raise SystemExit("a Lean source changed while the dump ran; rerun tools/lean_statements.py")
    for manifest in audit.MANIFESTS:
        if module_name(manifest) in hashes:
            text = audit.manifest_text(manifest, manifest_theorems[manifest])
            hashes[module_name(manifest)] = hashlib.sha256(text.encode()).hexdigest()
            declared[module_name(manifest)] = []

    def position(entry: str) -> tuple[int, ...]:
        """Ranged constants by their range, then the generated ones (no range) by name."""
        if entry.startswith("generated "):
            return (sys.maxsize,)
        return tuple(int(x) for x in re.split(r"[:-]", entry.split(" ", 1)[0]))

    return (HEADER + "".join(f"theorem {name}\n{entries[name]}" for name in names),
            PREDICATES_HEADER + "".join(f"module {m}\n" for m in all_modules)
            + "".join(f"{name}\n" for name in predicates),
            DECLARATIONS_HEADER + "".join(f"module {m} {hashes[m]}\n"
                                          + "".join(f"{e}\n" for e in sorted(declared[m], key=lambda e: (position(e), e)))
                                          for m in all_modules))


def locate(token: str) -> tuple[str, str] | None:
    """`name@Module` as (module, name); None for a token without a defining module."""
    name, at, module = token.rpartition("@")
    return (module, name) if at and name and module and module != "?" else None


def predicate_list(path: Path | None = None) -> tuple[set[tuple[str, str]], set[str]]:
    """The predicates of lean/predicates.txt as (module, name), and the modules the scan read.
    A line that is neither a `module` line nor `name@Module` (a list written before predicates
    carried their module) is a ValueError: the list is stale."""
    path = inventory_path(PREDICATES) if path is None else path
    found, modules = set(), set()
    if not path.is_file():
        return found, modules
    for line in path.read_text().splitlines():
        if not line or line.startswith("--"):
            continue
        if line.startswith("module "):
            modules.add(line.removeprefix("module "))
        elif (pair := locate(line)) is not None:
            found.add(pair)
        else:
            raise ValueError(f"{path.name}: {line!r} names no defining module; rerun tools/lean_statements.py")
    return found, modules


@dataclass(frozen=True)
class Declared:
    """A constant of the compiled environment with its source range ((line, column), 1-based
    lines), or None for a `generated` one: no range, and its name extends no constant."""
    name: str
    kind: str
    start: tuple[int, int] | None
    end: tuple[int, int] | None


KINDS = "theorem|def|instance|opaque|axiom|class|structure|inductive"
DECLARED = re.compile(rf"(?:(\d+):(\d+)-(\d+):(\d+)|generated) ({KINDS}) (.+)$")


def declaration_list(path: Path | None = None) -> tuple[dict[str, list[Declared]], dict[str, str]]:
    """The constants of lean/declarations.txt by defining module (their `name@Module` must name
    the module whose block lists them), and the source hash each module was compiled from. A
    malformed line is a ValueError: the list is stale or edited. A `generated` constant has no
    range (`Declared.start` is None)."""
    path = inventory_path(DECLARATIONS) if path is None else path
    found: dict[str, list[Declared]] = {}
    hashes: dict[str, str] = {}
    module = None
    for line in path.read_text().splitlines():
        if not line or line.startswith("--"):
            continue
        if line.startswith("module "):
            parts = line.split(" ")
            if len(parts) != 3 or parts[1] in hashes or not re.fullmatch(r"[0-9a-f]{64}", parts[2]):
                raise ValueError(f"{path.name}: {line!r} is not `module <Module> <sha256>`, once per module; "
                                 "rerun tools/lean_statements.py")
            module = parts[1]
            hashes[module] = parts[2]
            found[module] = []
            continue
        if module is None:
            raise ValueError(f"{path.name}: {line!r} is not a declaration of the module above it; "
                             "rerun tools/lean_statements.py")
        found[module].extend(declared_constants(module, [line], path.name))
    return found, hashes


def declared_constants(module: str, entries: list[str], label: str = "the dump") -> list[Declared]:
    """The constants of `module` from its declaration list entries (`<range> <kind> name@Module` or
    `generated <kind> name@Module`); an entry of another module or of another form is a ValueError."""
    found = []
    for line in entries:
        match = DECLARED.match(line)
        pair = locate(match[6]) if match else None
        if pair is None or pair[0] != module:
            raise ValueError(f"{label}: {line!r} is not a declaration of the module above it; "
                             "rerun tools/lean_statements.py")
        ranged = match[1] is not None
        found.append(Declared(pair[1], match[5], (int(match[1]), int(match[2])) if ranged else None,
                              (int(match[3]), int(match[4])) if ranged else None))
    return found


def predicates(path: Path | None = None) -> set[tuple[str, str]]:
    """The predicates in lean/predicates.txt, as (module, name)."""
    return predicate_list(path)[0]


def parse(text: str) -> dict[str, str]:
    """Map each `theorem <name>` header to the lines under it (newline-terminated)."""
    entries: dict[str, str] = {}
    name, body = None, []
    for line in text.splitlines():
        if line.startswith("theorem "):
            if name is not None:
                entries[name] = "".join(body)
            name, body = line.removeprefix("theorem ").strip(), []
        elif name is not None:
            body.append(line + "\n")
    if name is not None:
        entries[name] = "".join(body)
    return entries


def uses(body: str) -> set[tuple[str, str]] | None:
    """The constants on an entry's `-- uses` line as (defining module, full name), or None if the
    entry has no such line or a constant on it has no defining module (a dump written before the
    line carried modules)."""
    for line in body.splitlines():
        if line.startswith("  -- uses"):
            found = [locate(token) for token in line.removeprefix("  -- uses").split()]
            return None if None in found else set(found)
    return None


def difference(old: str, new: str) -> tuple[list[str], list[str], list[str]]:
    """(added, removed, changed) theorem names between two dumps."""
    a, b = parse(old), parse(new)
    return (sorted(set(b) - set(a)), sorted(set(a) - set(b)),
            sorted(name for name in set(a) & set(b) if a[name] != b[name]))


def show(added: list[str], removed: list[str], changed: list[str]) -> None:
    for label, names in (("added", added), ("removed", removed), ("changed", changed)):
        print(f"{label}: {len(names)}")
        for name in names:
            print(f"  {name}")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare a fresh dump with lean/statements.txt")
    parser.add_argument("--diff", nargs=2, type=Path, metavar=("OLD", "NEW"), help="compare two dumps")
    args = parser.parse_args(argv)
    if args.diff:
        added, removed, changed = difference(args.diff[0].read_text(), args.diff[1].read_text())
        show(added, removed, changed)
        return 1 if added or removed or changed else 0
    inputs = lean_inputs()
    fresh = dict(zip((STATEMENTS, PREDICATES, DECLARATIONS), dump_all(cache=True)))
    # The copies the readers get (`inventory_status`): a stale one differs from the dump, which records the hashes.
    olds = {name: path.read_text() if (path := inventory_status(name)[0]).is_file() else "" for name in fresh}
    if args.check:
        show(*difference(olds[STATEMENTS], fresh[STATEMENTS]))
        stale = [name for name in fresh if olds[name] != fresh[name]]
        for name in stale:
            print(f"{name} is stale; rerun python3 tools/lean_statements.py", file=sys.stderr)
        if stale:
            return 1
        print(f"PASS: {len(parse(fresh[STATEMENTS]))} statements, the predicate list and the declaration list unchanged")
        return 0
    written = [write_inventory(name, text, ROOT, inputs).relative_to(ROOT) for name, text in fresh.items()]
    show(*difference(olds[STATEMENTS], fresh[STATEMENTS]))
    print(f"wrote {written[0]} ({len(parse(fresh[STATEMENTS]))} statements), "
          f"{written[1]} ({len(predicates(ROOT / written[1]))} predicates) and {written[2]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
