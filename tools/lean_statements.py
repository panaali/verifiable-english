#!/usr/bin/env python3
"""Statement dump (bundle ST of docs/CONSOLIDATION-PLAN.md, step 0).

Writes the name and pretty-printed type of every theorem listed by `#print axioms` in
`lean/VE/Audit.lean` to `lean/statements.txt`, sorted by name. Each entry is

    theorem <name>
      <type, pretty-printed at width 100, indented by two spaces>
      -- uses <the constants of the elaborated type outside Init, Std, Lean and Lake, sorted>
      -- expr <hash of the elaborated type>

The hash is Lean's structural hash of the type expression, so a change the pretty printer hides
(an implicit argument, a universe) still shows. The `uses` line names every declaration the
statement mentions by its full name, dot notation included; `tools/trust_map.py` checks a tie
against it. A proof refactor leaves every kept entry
byte-identical; a step that adds, removes or restates theorems lists them.

    python3 tools/lean_statements.py           # rewrite lean/statements.txt (needs `lake build`)
    python3 tools/lean_statements.py --check   # exit 1 and list additions, removals and changes
    python3 tools/lean_statements.py --diff OLD NEW   # compare two dumps

The dump is produced by a Lean script that imports `VE` and runs in `lake env lean`; the script
is generated into a temporary file, so no Lean source under `lean/` changes.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
LEAN = ROOT / "lean"
OUTPUT = LEAN / "statements.txt"
PREDICATES = LEAN / "predicates.txt"
HEADER = ("-- Generated by tools/lean_statements.py from the `#print axioms` list of lean/VE/Audit.lean.\n"
          "-- Do not edit; rerun the tool after a Lean change (docs/CONSOLIDATION-PLAN.md, bundle ST).\n")
PREDICATES_HEADER = ("-- Generated by tools/lean_statements.py: every named non-theorem declaration of lean/ whose\n"
                     "-- type ends in Prop. tools/trust_map.py keeps them out of the executable classes C, D, G.\n")

sys.path.insert(0, str(LEAN))
from audit import code_only  # noqa: E402

SCRIPT = r"""
import Lean
import VE
open Lean Meta

set_option format.width 100 in
set_option pp.fullNames true in
#eval show MetaM Unit from do
  let some path ← IO.getEnv "VE_STATEMENT_NAMES"
    | throwError "VE_STATEMENT_NAMES is not set"
  let names := (← IO.FS.lines path).toList.filter (· ≠ "")
  let env ← getEnv
  let library : Name → Bool := fun c => match env.getModuleIdxFor? c with
    | some i => [`Init, `Std, `Lean, `Lake].contains (env.header.moduleNames[i.toNat]!).getRoot
    | none => false
  for s in names do
    let n ← resolveGlobalConstNoOverloadCore s.toName
    let info ← getConstInfo n
    let fmt ← ppExpr info.type
    let body := (toString fmt).splitOn "\n" |>.map ("  " ++ ·)
    let uses := (info.type.getUsedConstants.filter (! library ·)).map toString |>.qsort (· < ·)
    IO.println s!"theorem {s}"
    for line in body do
      IO.println line
    IO.println s!"  -- uses {" ".intercalate uses.toList}"
    IO.println s!"  -- expr {hash info.type}"
  -- Every other named declaration whose type ends in `Prop`: a predicate, not executable code.
  let mut predicates : Array String := #[]
  let project := (env.header.moduleNames.zip env.header.moduleData).filter fun (m, _) =>
    ![`Init, `Std, `Lean, `Lake].contains m.getRoot
  for n in project.flatMap (·.2.constNames) do
    let some info := env.find? n | continue
    if n.isInternalDetail || isAuxRecursor env n || isNoConfusion env n || (← isMatcher n) then
      continue
    match info with
    | .defnInfo _ | .inductInfo _ | .opaqueInfo _ | .axiomInfo _ =>
      let prop ← try forallTelescopeReducing info.type fun _ b => return b.isProp catch _ => pure false
      if prop then
        predicates := predicates.push (toString n)
    | _ => pure ()
  IO.println "-- predicates"
  for p in predicates.qsort (· < ·) do
    IO.println s!"predicate {p}"
"""


def audited_names(root: Path = ROOT) -> list[str]:
    text = code_only((root / "lean/VE/Audit.lean").read_text())
    return sorted(set(re.findall(r"^#print axioms (\S+)", text, re.M)))


def dump(root: Path = ROOT) -> str:
    return dump_all(root)[0]


def dump_all(root: Path = ROOT) -> tuple[str, str]:
    """The statement dump and the predicate list, from one Lean run."""
    names = audited_names(root)
    with tempfile.TemporaryDirectory(prefix="ve-statements-") as folder:
        listing = Path(folder) / "names.txt"
        listing.write_text("\n".join(names) + "\n")
        script = Path(folder) / "Statements.lean"
        script.write_text(SCRIPT)
        done = subprocess.run(["lake", "env", "lean", str(script)], cwd=root / "lean", text=True,
                              capture_output=True, env={**os.environ, "VE_STATEMENT_NAMES": str(listing)},
                              check=False)
    if done.returncode:
        raise SystemExit(f"lake env lean failed ({done.returncode}):\n{done.stderr}{done.stdout[-2000:]}")
    theorems, marker, rest = done.stdout.partition("-- predicates\n")
    entries = parse(theorems)
    if sorted(entries) != names or not marker:
        missing = sorted(set(names) - set(entries))[:10]
        raise SystemExit(f"the dump lists {len(entries)} theorems, the audit {len(names)}; missing {missing}")
    predicates = [line.removeprefix("predicate ") for line in rest.splitlines() if line.startswith("predicate ")]
    return (HEADER + "".join(f"theorem {name}\n{entries[name]}" for name in names),
            PREDICATES_HEADER + "".join(f"{name}\n" for name in predicates))


def predicates(path: Path | None = None) -> set[str]:
    """The names in lean/predicates.txt."""
    path = PREDICATES if path is None else path
    return {line for line in path.read_text().splitlines() if line and not line.startswith("--")} \
        if path.is_file() else set()


def parse(text: str) -> dict[str, str]:
    """Map each `theorem <name>` header to the lines under it (newline-terminated)."""
    entries: dict[str, str] = {}
    name, body = None, []
    for line in text.splitlines():
        if line.startswith("theorem "):
            if name is not None:
                entries[name] = "".join(body)
            name, body = line.removeprefix("theorem ").strip(), []
        elif name is not None:
            body.append(line + "\n")
    if name is not None:
        entries[name] = "".join(body)
    return entries


def uses(body: str) -> set[str] | None:
    """The full names on an entry's `-- uses` line, or None if the entry has none."""
    for line in body.splitlines():
        if line.startswith("  -- uses"):
            return set(line.removeprefix("  -- uses").split())
    return None


def difference(old: str, new: str) -> tuple[list[str], list[str], list[str]]:
    """(added, removed, changed) theorem names between two dumps."""
    a, b = parse(old), parse(new)
    return (sorted(set(b) - set(a)), sorted(set(a) - set(b)),
            sorted(name for name in set(a) & set(b) if a[name] != b[name]))


def show(added: list[str], removed: list[str], changed: list[str]) -> None:
    for label, names in (("added", added), ("removed", removed), ("changed", changed)):
        print(f"{label}: {len(names)}")
        for name in names:
            print(f"  {name}")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare a fresh dump with lean/statements.txt")
    parser.add_argument("--diff", nargs=2, type=Path, metavar=("OLD", "NEW"), help="compare two dumps")
    args = parser.parse_args(argv)
    if args.diff:
        added, removed, changed = difference(args.diff[0].read_text(), args.diff[1].read_text())
        show(added, removed, changed)
        return 1 if added or removed or changed else 0
    fresh, fresh_predicates = dump_all()
    old = OUTPUT.read_text() if OUTPUT.is_file() else ""
    old_predicates = PREDICATES.read_text() if PREDICATES.is_file() else ""
    if args.check:
        added, removed, changed = difference(old, fresh)
        show(added, removed, changed)
        stale = [path for path, a, b in ((OUTPUT, old, fresh), (PREDICATES, old_predicates, fresh_predicates))
                 if a != b]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is stale; rerun python3 tools/lean_statements.py", file=sys.stderr)
        if stale:
            return 1
        print(f"PASS: {len(parse(fresh))} statements and the predicate list unchanged")
        return 0
    OUTPUT.write_text(fresh)
    PREDICATES.write_text(fresh_predicates)
    show(*difference(old, fresh))
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(parse(fresh))} statements) and "
          f"{PREDICATES.relative_to(ROOT)} ({fresh_predicates.count(chr(10)) - 2} predicates)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
