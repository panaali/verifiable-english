PRELUDE = r"""
open Lean Meta

/-- A constant as `name@module`: the name a reader writes (a private name without its prefix) and
the module that defines it, so that namesakes in two modules stay apart. -/
def located (env : Environment) (c : Name) : String :=
  let module := match env.getModuleIdxFor? c with
    | some i => toString env.header.moduleNames[i.toNat]!
    | none => "?"
  s!"{(privateToUserName? c).getD c}@{module}"

/-- The kind of a declaration as the environment records it; none for a constructor, recursor or
quotient constant (each part of the type that declares it). -/
def kindOf (env : Environment) (c : Name) : ConstantInfo → Option String
  | .thmInfo _ => some "theorem"
  | .defnInfo _ => some (if isInstanceCore env c then "instance" else "def")
  | .opaqueInfo _ => some (if isInstanceCore env c then "instance" else "opaque")
  | .axiomInfo _ => some "axiom"
  | .inductInfo _ => some (if isClass env c then "class" else if isStructure env c then "structure" else "inductive")
  | _ => none

/-- Whether a proper prefix of `c` is a constant (of any module): a constant Lean generates for a
declaration without giving it a range (an equation lemma, `below`, a `match` splitter) extends
that declaration's name. -/
def extendsConstant (env : Environment) : Name → Bool
  | .str p _ | .num p _ => (env.find? p).isSome || extendsConstant env p
  | .anonymous => false

/-- For every constant of `module` with a source range (generated recursors, `noConfusion` and
matchers left out): `declaration <line>:<column>-<line>:<column> <kind> name@module`, the range
running from the docstring or first attribute to the end of the declaration; for every one
without a range whose name extends no constant (what `run_elab` or `addDecl` adds), `generated
<kind> name@module`, a constant no line of the file can be placed for. Then every named
non-theorem declaration whose type ends in `Prop` (a predicate, not executable code), and the line
`module <module>`. A name is never filtered by its spelling: an internal-looking name with a source
range of its own (`def _x`) is a declaration and a predicate like any other. -/
def printPredicates (module : Name) : MetaM Unit := do
  let env ← getEnv
  let some i := env.getModuleIdx? module | throwError "{module} is not imported"
  for n in env.header.moduleData[i.toNat]!.constNames do
    let some info := env.find? n | continue
    if isAuxRecursor env n || isNoConfusion env n || (← isMatcher n) then
      continue
    let some kind := kindOf env n info | continue
    let ranges ← findDeclarationRanges? n
    if let some r := ranges then
      IO.println s!"declaration {r.range.pos.line}:{r.range.pos.column}-{r.range.endPos.line}:{r.range.endPos.column} {kind} {located env n}"
    -- A realized lemma of a public matcher may be private (`_private.M.0.f.match_1.eq_1`).
    else if !(extendsConstant env n || extendsConstant env ((privateToUserName? n).getD n)) then
      IO.println s!"generated {kind} {located env n}"
    if ((privateToUserName? n).getD n).isInternalDetail && ranges.isNone then
      continue
    if kind != "theorem" then
      let prop ← try forallTelescopeReducing info.type fun _ b => return b.isProp catch _ => pure false
      if prop then
        IO.println s!"predicate {located env n}"
  IO.println s!"module {module}"
"""

# The predicates of every module of the tree that `VE` imports; each other module (an executable's
# root, a file nothing imports) is listed `outside` and read by ALONE.
TREE = "import Lean\nimport VE\n" + PRELUDE + r"""
#eval show MetaM Unit from do
  let some treePath ← IO.getEnv "VE_TREE_MODULES"
    | throwError "VE_TREE_MODULES is not set"
  let tree := (← IO.FS.lines treePath).toList.filter (· ≠ "") |>.map String.toName
  let env ← getEnv
  for m in tree do
    if (env.getModuleIdx? m).isSome then
      printPredicates m
    else
      IO.println s!"outside {m}"
"""

# The statements of the theorems named in VE_STATEMENT_NAMES.
SCRIPT = "import Lean\nimport VE\n" + PRELUDE + r"""
set_option format.width 100 in
set_option pp.fullNames true in
#eval show MetaM Unit from do
  let some path ← IO.getEnv "VE_STATEMENT_NAMES"
    | throwError "VE_STATEMENT_NAMES is not set"
  let names := (← IO.FS.lines path).toList.filter (· ≠ "")
  let env ← getEnv
  let library : Name → Bool := fun c => match env.getModuleIdxFor? c with
    | some i => [`Init, `Std, `Lean, `Lake].contains (env.header.moduleNames[i.toNat]!).getRoot
    | none => false
  for s in names do
    let n ← resolveGlobalConstNoOverloadCore s.toName
    let info ← getConstInfo n
    let fmt ← ppExpr info.type
    let body := (toString fmt).splitOn "\n" |>.map ("  " ++ ·)
    let uses := (info.type.getUsedConstants.filter (! library ·)).map (located env) |>.qsort (· < ·)
    IO.println s!"theorem {s}"
    for line in body do
      IO.println line
    if uses.isEmpty then
      IO.println "  -- uses"
    else
      IO.println s!"  -- uses {" ".intercalate uses.toList}"
    IO.println s!"  -- expr {hash info.type}"
"""

