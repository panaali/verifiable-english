#!/usr/bin/env python3
"""Statement dump (bundle ST of docs/CONSOLIDATION-PLAN.md, step 0).

Writes the name and pretty-printed type of every theorem listed by `#print axioms` in
`lean/VE/Audit.lean` to `lean/statements.txt`, sorted by name. The list is the one `lean/audit.py
--write` generates from the declaration list below, taken from this run's dump, so the order is:
the compiled environment, then `declarations.txt` and the statements, then the manifests. Each entry is

    theorem <name>
      <type, pretty-printed at width 100, indented by two spaces>
      -- uses <the constants of the elaborated type outside Init, Std, Lean and Lake, sorted>
      -- expr <hash of the elaborated type>

The hash is Lean's structural hash of the type expression, so a change the pretty printer hides
(an implicit argument, a universe) still shows. The `uses` line names every declaration the
statement mentions as `name@Module`: its full name, dot notation included, and the module that
defines it, so a namesake in another module (two files nothing imports together may both define
`VE.Demo.anchor`) is a different constant; `tools/trust_map.py` checks a tie against it. A proof
refactor leaves every kept entry byte-identical; a step that adds, removes or restates theorems
lists them.

`lean/predicates.txt` lists, as `name@Module`, every named non-theorem declaration whose type ends
in `Prop`, over every module of the tree (a `module` line each): the modules `VE` imports, and each
other file (an executable's root, a file nothing imports) imported alone.

`lean/declarations.txt` lists, for every module of the tree, the SHA-256 of the source file that was
compiled (`module <Module> <hash>`) and every constant of the compiled module with a source range
(`<line>:<column>-<line>:<column> <kind> name@Module`), as the environment records it: the
declaration's name, kind and range come from Lean, never from reading the source text, so a
quoted name (`«x»`), a binder written without a space or any other spelling cannot change them.
A constant without a range whose name extends no constant (one `run_elab` or `addDecl` added) is
listed `generated <kind> name@Module`; one that extends a constant (an equation lemma, `below`) is
that constant's. `tools/trust_map.py` classifies these declarations and fails on generated ones.

    python3 tools/lean_statements.py           # rewrite lean/statements.txt (builds every module)
    python3 tools/lean_statements.py --check   # exit 1 and list additions, removals and changes
    python3 tools/lean_statements.py --diff OLD NEW   # compare two dumps

The dump is produced by a Lean script that imports `VE` and runs in `lake env lean`; the script
is generated into a temporary file, so no Lean source under `lean/` changes.
"""
from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
import hashlib
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
LEAN = ROOT / "lean"
OUTPUT = LEAN / "statements.txt"
PREDICATES = LEAN / "predicates.txt"
DECLARATIONS = LEAN / "declarations.txt"
HEADER = ("-- Generated by tools/lean_statements.py from the `#print axioms` list of lean/VE/Audit.lean.\n"
          "-- Do not edit; rerun the tool after a Lean change (docs/CONSOLIDATION-PLAN.md, bundle ST).\n")
PREDICATES_HEADER = ("-- Generated by tools/lean_statements.py: every named non-theorem declaration of lean/ whose\n"
                     "-- type ends in Prop, as name@Module, over the modules listed. tools/trust_map.py keeps them\n"
                     "-- out of the executable classes C, D, G.\n")
DECLARATIONS_HEADER = ("-- Generated by tools/lean_statements.py from the compiled environment: per module, the\n"
                       "-- SHA-256 of the compiled source and every constant with a source range, as\n"
                       "-- <line>:<column>-<line>:<column> <kind> name@Module, and every one without a range whose\n"
                       "-- name extends no constant, as generated <kind> name@Module. tools/trust_map.py classifies\n"
                       "-- them (and fails on a generated one).\n")

sys.path.insert(0, str(LEAN))
import audit  # noqa: E402
from audit import code_only  # noqa: E402

PRELUDE = r"""
open Lean Meta

/-- A constant as `name@module`: the name a reader writes (a private name without its prefix) and
the module that defines it, so that namesakes in two modules stay apart. -/
def located (env : Environment) (c : Name) : String :=
  let module := match env.getModuleIdxFor? c with
    | some i => toString env.header.moduleNames[i.toNat]!
    | none => "?"
  s!"{(privateToUserName? c).getD c}@{module}"

/-- The kind of a declaration as the environment records it; none for a constructor, recursor or
quotient constant (each part of the type that declares it). -/
def kindOf (env : Environment) (c : Name) : ConstantInfo → Option String
  | .thmInfo _ => some "theorem"
  | .defnInfo _ => some (if isInstanceCore env c then "instance" else "def")
  | .opaqueInfo _ => some (if isInstanceCore env c then "instance" else "opaque")
  | .axiomInfo _ => some "axiom"
  | .inductInfo _ => some (if isClass env c then "class" else if isStructure env c then "structure" else "inductive")
  | _ => none

/-- Whether a proper prefix of `c` is a constant (of any module): a constant Lean generates for a
declaration without giving it a range (an equation lemma, `below`, a `match` splitter) extends
that declaration's name. -/
def extendsConstant (env : Environment) : Name → Bool
  | .str p _ | .num p _ => (env.find? p).isSome || extendsConstant env p
  | .anonymous => false

/-- For every constant of `module` with a source range (generated recursors, `noConfusion` and
matchers left out): `declaration <line>:<column>-<line>:<column> <kind> name@module`, the range
running from the docstring or first attribute to the end of the declaration; for every one
without a range whose name extends no constant (what `run_elab` or `addDecl` adds), `generated
<kind> name@module`, a constant no line of the file can be placed for. Then every named
non-theorem declaration whose type ends in `Prop` (a predicate, not executable code), and the line
`module <module>`. A name is never filtered by its spelling: an internal-looking name with a source
range of its own (`def _x`) is a declaration and a predicate like any other. -/
def printPredicates (module : Name) : MetaM Unit := do
  let env ← getEnv
  let some i := env.getModuleIdx? module | throwError "{module} is not imported"
  for n in env.header.moduleData[i.toNat]!.constNames do
    let some info := env.find? n | continue
    if isAuxRecursor env n || isNoConfusion env n || (← isMatcher n) then
      continue
    let some kind := kindOf env n info | continue
    let ranges ← findDeclarationRanges? n
    if let some r := ranges then
      IO.println s!"declaration {r.range.pos.line}:{r.range.pos.column}-{r.range.endPos.line}:{r.range.endPos.column} {kind} {located env n}"
    -- A realized lemma of a public matcher may be private (`_private.M.0.f.match_1.eq_1`).
    else if !(extendsConstant env n || extendsConstant env ((privateToUserName? n).getD n)) then
      IO.println s!"generated {kind} {located env n}"
    if ((privateToUserName? n).getD n).isInternalDetail && ranges.isNone then
      continue
    if kind != "theorem" then
      let prop ← try forallTelescopeReducing info.type fun _ b => return b.isProp catch _ => pure false
      if prop then
        IO.println s!"predicate {located env n}"
  IO.println s!"module {module}"
"""

# The predicates of every module of the tree that `VE` imports; each other module (an executable's
# root, a file nothing imports) is listed `outside` and read by ALONE.
TREE = "import Lean\nimport VE\n" + PRELUDE + r"""
#eval show MetaM Unit from do
  let some treePath ← IO.getEnv "VE_TREE_MODULES"
    | throwError "VE_TREE_MODULES is not set"
  let tree := (← IO.FS.lines treePath).toList.filter (· ≠ "") |>.map String.toName
  let env ← getEnv
  for m in tree do
    if (env.getModuleIdx? m).isSome then
      printPredicates m
    else
      IO.println s!"outside {m}"
"""

# The statements of the theorems named in VE_STATEMENT_NAMES.
SCRIPT = "import Lean\nimport VE\n" + PRELUDE + r"""
set_option format.width 100 in
set_option pp.fullNames true in
#eval show MetaM Unit from do
  let some path ← IO.getEnv "VE_STATEMENT_NAMES"
    | throwError "VE_STATEMENT_NAMES is not set"
  let names := (← IO.FS.lines path).toList.filter (· ≠ "")
  let env ← getEnv
  let library : Name → Bool := fun c => match env.getModuleIdxFor? c with
    | some i => [`Init, `Std, `Lean, `Lake].contains (env.header.moduleNames[i.toNat]!).getRoot
    | none => false
  for s in names do
    let n ← resolveGlobalConstNoOverloadCore s.toName
    let info ← getConstInfo n
    let fmt ← ppExpr info.type
    let body := (toString fmt).splitOn "\n" |>.map ("  " ++ ·)
    let uses := (info.type.getUsedConstants.filter (! library ·)).map (located env) |>.qsort (· < ·)
    IO.println s!"theorem {s}"
    for line in body do
      IO.println line
    if uses.isEmpty then
      IO.println "  -- uses"
    else
      IO.println s!"  -- uses {" ".intercalate uses.toList}"
    IO.println s!"  -- expr {hash info.type}"
"""

# The predicates of one module, imported alone (after `import Lean` and `import <module>`): two
# executables' roots may define the same name, so they cannot share one environment.
ALONE = PRELUDE + r"""
#eval show MetaM Unit from do
  let some m ← IO.getEnv "VE_PREDICATE_MODULE"
    | throwError "VE_PREDICATE_MODULE is not set"
  printPredicates m.toName
"""


def audited_names(root: Path = ROOT) -> list[str]:
    text = code_only((root / "lean/VE/Audit.lean").read_text())
    return sorted(set(re.findall(r"^#print axioms (\S+)", text, re.M)))


def dump(root: Path = ROOT) -> str:
    return dump_all(root)[0]


def sources(root: Path = ROOT) -> list[Path]:
    """Every Lean file of the tree (`lean/`, build output excluded)."""
    lean = root / "lean"
    return [p for p in sorted(lean.rglob("*.lean")) if ".lake" not in p.relative_to(lean).parts]


def module_name(key: str) -> str:
    """The Lean module of a file given by its path under `lean/` (`VE/Demo.lean` is `VE.Demo`)."""
    return key.removesuffix(".lean").replace("/", ".")


def tree_modules(root: Path = ROOT) -> list[str]:
    return [module_name(p.relative_to(root / "lean").as_posix()) for p in sources(root)]


def run_lean(root: Path, folder: Path, script: str, label: str, env: dict[str, str]) -> str:
    path = folder / f"{label}.lean"
    path.write_text(script)
    done = subprocess.run(["lake", "env", "lean", str(path)], cwd=root / "lean", text=True, capture_output=True,
                          check=False, env={**os.environ, **env})
    if done.returncode:
        raise SystemExit(f"lake env lean failed on {label} ({done.returncode}):\n{done.stderr}{done.stdout[-2000:]}")
    return done.stdout


def source_hash(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def dump_all(root: Path = ROOT) -> tuple[str, str, str]:
    """The statement dump, the predicate list and the declaration list over every module of the
    tree (each built first: a file no target imports has no object file until it is named). One
    Lean run imports `VE`; each module outside it is read by its own run, in parallel. The
    statements are those of the theorems of `lean/VE/Audit.lean` as `lean/audit.py --write`
    generates it from this declaration list, read by a second run that imports `VE`; each audit
    manifest's hash is that of its generated text, so the list is current once the manifests are."""
    modules = tree_modules(root)
    built = subprocess.run(["lake", "build", *modules], cwd=root / "lean", text=True, capture_output=True,
                           check=False)
    if built.returncode:
        raise SystemExit(f"lake build of the tree's modules failed ({built.returncode}):\n"
                         f"{built.stderr}{built.stdout[-2000:]}")
    hashes = {module_name(p.relative_to(root / "lean").as_posix()): source_hash(p) for p in sources(root)}
    with tempfile.TemporaryDirectory(prefix="ve-statements-") as name:
        folder = Path(name)
        (folder / "modules.txt").write_text("\n".join(modules) + "\n")
        rest = run_lean(root, folder, TREE, "Tree", {"VE_TREE_MODULES": str(folder / "modules.txt")})
        outside = [line.removeprefix("outside ") for line in rest.splitlines() if line.startswith("outside ")]
        with ThreadPoolExecutor(max_workers=min(8, os.cpu_count() or 1)) as pool:
            alone = list(pool.map(lambda m: run_lean(root, folder, f"import Lean\nimport {m}\n" + ALONE,
                                                     f"Alone{outside.index(m)}", {"VE_PREDICATE_MODULE": m}),
                                  outside))
        lines = [line for text in (rest, *alone) for line in text.splitlines()]
        declared: dict[str, list[str]] = {}
        pending: list[str] = []
        for line in lines:
            if line.startswith("declaration "):
                pending.append(line.removeprefix("declaration "))
            elif line.startswith("generated "):
                pending.append(line)
            elif line.startswith("module "):
                declared[line.removeprefix("module ")], pending = pending, []
        try:
            manifests = audit.manifest_theorems({m: declared_constants(m, declared.get(m, [])) for m in modules})
        except (ValueError, AssertionError) as error:
            raise SystemExit(f"the declaration dump cannot give the audit manifests: {error}")
        names = sorted(manifests[audit.MANIFESTS[0]])
        (folder / "names.txt").write_text("\n".join(names) + "\n")
        theorems = run_lean(root, folder, SCRIPT, "Statements", {"VE_STATEMENT_NAMES": str(folder / "names.txt")})
    entries = parse(theorems)
    if sorted(entries) != names:
        missing = sorted(set(names) - set(entries))[:10]
        raise SystemExit(f"the dump lists {len(entries)} theorems, the audit {len(names)}; missing {missing}")
    scanned = sorted(line.removeprefix("module ") for line in lines if line.startswith("module "))
    if scanned != sorted(modules):
        raise SystemExit(f"the predicate scan read {len(scanned)} modules of the tree's {len(modules)}: "
                         f"missing {sorted(set(modules) - set(scanned))[:10]}")
    predicates = sorted(line.removeprefix("predicate ") for line in lines if line.startswith("predicate "))
    if hashes != {m: source_hash(p) for m, p in zip(modules, sources(root))}:
        raise SystemExit("a Lean source changed while the dump ran; rerun tools/lean_statements.py")
    for manifest in audit.MANIFESTS:
        if module_name(manifest) in hashes:
            text = audit.manifest_text(manifest, manifests[manifest])
            hashes[module_name(manifest)] = hashlib.sha256(text.encode()).hexdigest()

    def position(entry: str) -> tuple[int, ...]:
        """Ranged constants by their range, then the generated ones (no range) by name."""
        if entry.startswith("generated "):
            return (sys.maxsize,)
        return tuple(int(x) for x in re.split(r"[:-]", entry.split(" ", 1)[0]))

    return (HEADER + "".join(f"theorem {name}\n{entries[name]}" for name in names),
            PREDICATES_HEADER + "".join(f"module {m}\n" for m in modules)
            + "".join(f"{name}\n" for name in predicates),
            DECLARATIONS_HEADER + "".join(f"module {m} {hashes[m]}\n"
                                          + "".join(f"{e}\n" for e in sorted(declared[m], key=lambda e: (position(e), e)))
                                          for m in modules))


def locate(token: str) -> tuple[str, str] | None:
    """`name@Module` as (module, name); None for a token without a defining module."""
    name, at, module = token.rpartition("@")
    return (module, name) if at and name and module and module != "?" else None


def predicate_list(path: Path | None = None) -> tuple[set[tuple[str, str]], set[str]]:
    """The predicates of lean/predicates.txt as (module, name), and the modules the scan read.
    A line that is neither a `module` line nor `name@Module` (a list written before predicates
    carried their module) is a ValueError: the list is stale."""
    path = PREDICATES if path is None else path
    found, modules = set(), set()
    if not path.is_file():
        return found, modules
    for line in path.read_text().splitlines():
        if not line or line.startswith("--"):
            continue
        if line.startswith("module "):
            modules.add(line.removeprefix("module "))
        elif (pair := locate(line)) is not None:
            found.add(pair)
        else:
            raise ValueError(f"{path.name}: {line!r} names no defining module; rerun tools/lean_statements.py")
    return found, modules


@dataclass(frozen=True)
class Declared:
    """A constant of the compiled environment with its source range ((line, column), 1-based
    lines), or None for a `generated` one: no range, and its name extends no constant."""
    name: str
    kind: str
    start: tuple[int, int] | None
    end: tuple[int, int] | None


KINDS = "theorem|def|instance|opaque|axiom|class|structure|inductive"
DECLARED = re.compile(rf"(?:(\d+):(\d+)-(\d+):(\d+)|generated) ({KINDS}) (.+)$")


def declaration_list(path: Path | None = None) -> tuple[dict[str, list[Declared]], dict[str, str]]:
    """The constants of lean/declarations.txt by defining module (their `name@Module` must name
    the module whose block lists them), and the source hash each module was compiled from. A
    malformed line is a ValueError: the list is stale or edited. A `generated` constant has no
    range (`Declared.start` is None)."""
    path = DECLARATIONS if path is None else path
    found: dict[str, list[Declared]] = {}
    hashes: dict[str, str] = {}
    module = None
    for line in path.read_text().splitlines():
        if not line or line.startswith("--"):
            continue
        if line.startswith("module "):
            parts = line.split(" ")
            if len(parts) != 3 or parts[1] in hashes or not re.fullmatch(r"[0-9a-f]{64}", parts[2]):
                raise ValueError(f"{path.name}: {line!r} is not `module <Module> <sha256>`, once per module; "
                                 "rerun tools/lean_statements.py")
            module = parts[1]
            hashes[module] = parts[2]
            found[module] = []
            continue
        if module is None:
            raise ValueError(f"{path.name}: {line!r} is not a declaration of the module above it; "
                             "rerun tools/lean_statements.py")
        found[module].extend(declared_constants(module, [line], path.name))
    return found, hashes


def declared_constants(module: str, entries: list[str], label: str = "the dump") -> list[Declared]:
    """The constants of `module` from its declaration list entries (`<range> <kind> name@Module` or
    `generated <kind> name@Module`); an entry of another module or of another form is a ValueError."""
    found = []
    for line in entries:
        match = DECLARED.match(line)
        pair = locate(match[6]) if match else None
        if pair is None or pair[0] != module:
            raise ValueError(f"{label}: {line!r} is not a declaration of the module above it; "
                             "rerun tools/lean_statements.py")
        ranged = match[1] is not None
        found.append(Declared(pair[1], match[5], (int(match[1]), int(match[2])) if ranged else None,
                              (int(match[3]), int(match[4])) if ranged else None))
    return found


def predicates(path: Path | None = None) -> set[tuple[str, str]]:
    """The predicates in lean/predicates.txt, as (module, name)."""
    return predicate_list(path)[0]


def parse(text: str) -> dict[str, str]:
    """Map each `theorem <name>` header to the lines under it (newline-terminated)."""
    entries: dict[str, str] = {}
    name, body = None, []
    for line in text.splitlines():
        if line.startswith("theorem "):
            if name is not None:
                entries[name] = "".join(body)
            name, body = line.removeprefix("theorem ").strip(), []
        elif name is not None:
            body.append(line + "\n")
    if name is not None:
        entries[name] = "".join(body)
    return entries


def uses(body: str) -> set[tuple[str, str]] | None:
    """The constants on an entry's `-- uses` line as (defining module, full name), or None if the
    entry has no such line or a constant on it has no defining module (a dump written before the
    line carried modules)."""
    for line in body.splitlines():
        if line.startswith("  -- uses"):
            found = [locate(token) for token in line.removeprefix("  -- uses").split()]
            return None if None in found else set(found)
    return None


def difference(old: str, new: str) -> tuple[list[str], list[str], list[str]]:
    """(added, removed, changed) theorem names between two dumps."""
    a, b = parse(old), parse(new)
    return (sorted(set(b) - set(a)), sorted(set(a) - set(b)),
            sorted(name for name in set(a) & set(b) if a[name] != b[name]))


def show(added: list[str], removed: list[str], changed: list[str]) -> None:
    for label, names in (("added", added), ("removed", removed), ("changed", changed)):
        print(f"{label}: {len(names)}")
        for name in names:
            print(f"  {name}")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare a fresh dump with lean/statements.txt")
    parser.add_argument("--diff", nargs=2, type=Path, metavar=("OLD", "NEW"), help="compare two dumps")
    args = parser.parse_args(argv)
    if args.diff:
        added, removed, changed = difference(args.diff[0].read_text(), args.diff[1].read_text())
        show(added, removed, changed)
        return 1 if added or removed or changed else 0
    fresh, fresh_predicates, fresh_declarations = dump_all()
    old = OUTPUT.read_text() if OUTPUT.is_file() else ""
    olds = {path: path.read_text() if path.is_file() else "" for path in (PREDICATES, DECLARATIONS)}
    if args.check:
        added, removed, changed = difference(old, fresh)
        show(added, removed, changed)
        stale = [path for path, a, b in ((OUTPUT, old, fresh), (PREDICATES, olds[PREDICATES], fresh_predicates),
                                         (DECLARATIONS, olds[DECLARATIONS], fresh_declarations)) if a != b]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is stale; rerun python3 tools/lean_statements.py", file=sys.stderr)
        if stale:
            return 1
        print(f"PASS: {len(parse(fresh))} statements, the predicate list and the declaration list unchanged")
        return 0
    OUTPUT.write_text(fresh)
    PREDICATES.write_text(fresh_predicates)
    DECLARATIONS.write_text(fresh_declarations)
    show(*difference(old, fresh))
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(parse(fresh))} statements), "
          f"{PREDICATES.relative_to(ROOT)} ({len(predicates())} predicates) and {DECLARATIONS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
