"""Write or check `lean/VE/Question/Fixtures.lean`, the Lean `#guard`s of the Q1 fixture table.

    python tools/question_fixtures.py --write
    python tools/question_fixtures.py --check

The table is `tests/question_fixtures.py` (docs/spec/question-answering.md section 7). For each frame the file holds
the `english.question` case the relay sends (the environment, the lexicon of the English reader's producer, the
mode and cap), and for each fixture a `#guard` that `VE.Question.Run.questionCase` answers the question with the
table's result. `lake build` evaluates the guards, so the table, Lean and the running service (the suite's live
check) are compared three ways. `--check` fails when the file differs from its rendering.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

TARGET = ROOT / "lean/VE/Question/Fixtures.lean"

HEADER = '''import VE.Question.Run

/-! The Q1 fixture table (`tests/question_fixtures.py`, docs/spec/question-answering.md section 7) as `#guard`s.
Generated by `python3 tools/question_fixtures.py --write`; do not edit. Each frame is the `english.question` case
the relay sends for a fixture's vocabulary, without its id and question; each guard runs `Run.questionCase` on the
frame with the question and compares the result, without its identities and with the witnesses as their number,
with the table's. -/

namespace VE.Question.Fixtures
open Lean

/-- The table's form of `english.question`'s result: without identities, the witnesses as their number,
compressed; a frame or case that is not read gives its message. -/
def answer (frame question : String) : String :=
  match Json.parse frame with
  | .error e => "frame: " ++ e
  | .ok j =>
    let j := ((j.setObjVal! "id" (.str "english.question")).setObjVal! "source" (.str question)).setObjVal!
      "question" (.str question)
    match Run.questionCase j with
    | .error e => "error: " ++ e
    | .ok row => match VE.Bridge.fields (row.getObjValD "result") with
      | .error e => "result: " ++ e
      | .ok fs => (Json.mkObj (fs.filterMap fun (k, v) => if k == "identities" then none
          else some (k, if k == "witnesses" then (match v with | .arr a => toJson a.size | _ => v) else v))).compress

def expect (frame question expected : String) : Bool :=
  match Json.parse expected with
  | .ok e => answer frame question == e.compress
  | .error _ => false
'''


def lean_string(text: str) -> str:
    out = []
    for ch in text:
        if ch in '\\"':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 0x20 or ord(ch) == 0x7f:
            out.append(f"\\x{ord(ch):02x}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def frame_name(frame: str) -> str:
    return "frame" + "".join(part.capitalize() for part in frame.replace("-", " ").split())


def render() -> str:
    import question_fixtures as F
    frames = list(dict.fromkeys(frame for _, frame, _, _ in F.FIXTURES))
    lines = [HEADER]
    for frame in frames:
        case = F.request(frame, "?")
        for key in ("id", "source", "question"):
            del case[key]
        lines.append(f"/-- The `{frame}` frame. -/")
        lines.append(f"def {frame_name(frame)} : String :=\n  {lean_string(json.dumps(case, ensure_ascii=False, sort_keys=True))}\n")
    for fixture, frame, question, answer in F.FIXTURES:
        expected = json.dumps(answer, ensure_ascii=False, sort_keys=True)
        lines.append(f"-- {fixture}")
        lines.append(f"#guard expect {frame_name(frame)} {lean_string(question)}\n  {lean_string(expected)}")
    lines.append("\nend VE.Question.Fixtures\n")
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        TARGET.write_text(text)
        return 0
    if not TARGET.exists() or TARGET.read_text() != text:
        print(f"{TARGET.relative_to(ROOT)} differs from the fixture table; run --write")
        return 1
    print("PASS: the Lean fixture guards are the fixture table")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
