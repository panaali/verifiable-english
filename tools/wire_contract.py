def unit_label(unit):
    """The Lean name of a unit's table module: the words of the unit's name, capitalised and joined."""
    return "".join(word.capitalize() for word in unit.split("@", 1)[0].split("-"))


def unit_paths(unit):
    """The paths of a unit, relative to the checkout: its examples, its English table, its generated Lean
    module and its fault catalogue's index."""
    return {"examples": f"ve/wire_contract/examples/{unit}",
            "english": f"docs/spec/{unit.split('@', 1)[0]}-wire-table.md",
            "lean": f"lean/VE/WireContract/Tables/{unit_label(unit)}.lean",
            "catalogue": f"conformance/wire-contract/{unit}-catalogue.json"}


def _included(contract):
    """The contracts a contract includes, anywhere in its table, in order of first occurrence."""
    found = []
    def walk(entries):
        for entry in entries:
            if "each" in entry:
                walk(entry["checks"])
            elif entry.get("kind") == "include" and entry["contract"] not in found:
                found.append(entry["contract"])
    for phase in contract["phases"]:
        walk(phase["checks"])
    return found


def generated_lean(contracts, limits, names):
    """The Lean modules are determined by locked contract data alone."""
    limits_hash, names_hash = _hash(limits), _hash(names)
    def definitions(label, body, source, digest):
        return (f"/- GENERATED by tools/wire_contract.py from {source}, revision 1,\n"
                f"   sha256 {digest}; limits {limits_hash}; names {names_hash}. Do not edit. -/\n"
                "import VE.WireContract.Table\n\n"
                f"namespace VE.WireContract.{label}\n" + body +
                f"end VE.WireContract.{label}\n")
    rendered = {
        "lean/VE/WireContract/Limits.lean": definitions(
            "Limits", "".join(f"def {key} : Nat := {val}\n" for key, val in sorted(limits.items())),
            "ve/wire_contract/limits.json", limits_hash),
        "lean/VE/WireContract/Names.lean": definitions(
            "Names", "".join(f"def {key} : VE.WireContract.NameClass := {lean_name_class(val)}\n"
                               for key, val in sorted(names.items())),
            "ve/wire_contract/names.json", names_hash),
    }
    for unit in UNITS:
        if unit not in contracts:
            continue
        value = contracts[unit]
        # An included contract's entries are inlined (`tools/wire_contract_lean.py`), so its hash is named
        # in the header too: a revision of it regenerates the including module (wire-contract-s5.md 2.10).
        includes = [(name, _hash(contracts[name])) for name in _included(value) if name in contracts]
        rendered[unit_paths(unit)["lean"]] = lean_module(
            unit_label(unit), f"def table : VE.WireContract.Table :=\n  {lean_table(value, contracts, limits, names)}\n",
            f"ve/wire_contract/{unit}.json", value["revision"], _hash(value), limits_hash, names_hash,
            includes=includes)
    corpus_dir = ROOT / "conformance/wire-contract/contracts"
    corpus = {unit: loads_json((corpus_dir / f"{unit}.json").read_bytes()) for unit, _ in CORPUS}
    corpus_limits = loads_json((corpus_dir / "limits.json").read_bytes())
    corpus_names = loads_json((corpus_dir / "names.json").read_bytes())
    sections = []
    for unit, label in CORPUS:
        c = corpus[unit]
        sections.append(f"namespace VE.WireContract.Tables.{label}\n"
                        f"def table : VE.WireContract.Table :=\n  {lean_table(c, corpus, corpus_limits, corpus_names)}\n"
                        f"end VE.WireContract.Tables.{label}\n")
    rendered["lean/VE/WireContract/Tables/Corpus.lean"] = (
        "/- GENERATED by tools/wire_contract.py from conformance/wire-contract/contracts/, revision 1,\n"
        f"   sha256 {_hash(list(corpus.values()))}; limits {_hash(corpus_limits)}; names {_hash(corpus_names)}. Do not edit. -/\n"
        "import VE.WireContract.Table\n\n" + "\n".join(sections))
    return rendered


def _id_key(value):
    return tuple(tuple((0, int(run)) if run.isdigit() else (1, run)
                       for run in PART.findall(part)) for part in value.split("."))


def _comparable(a, b):
    left, right = _id_key(a), _id_key(b)
    for x, y in zip(left, right):
        for p, q in zip(x, y):
            if p[0] != q[0]:
                return False
            if p != q:
                return True
        if len(x) != len(y):
            return True
    return True


def _type_word(form):
    atoms = {"null": "null", "boolean": "a Boolean", "integer": "an integer",
             "string": "a string", "array": "an array", "object": "an object"}
    plurals = {"null": "nulls", "boolean": "Booleans", "integer": "integers",
               "string": "strings", "array": "arrays", "object": "objects"}
    if type(form) is list:
        return " or ".join(_type_word(f) for f in form)
    if type(form) is str:
        return atoms[form]
    if "array_of" in form:
        return "an array of " + plurals[form["array_of"]]
    return "an array of exactly " + str(len(form["tuple"])) + " elements: " + ", ".join(
        atoms[a] for a in form["tuple"])


def _place(loc, groups=()):
    """A location in words (3.1). Inside groups, `@n` is the item of the group `n` levels out, named by
    that group's id, so every sentence names the group whose item it reads: `the `ranks` item`."""
    match = re.fullmatch(r"@([0-9]*)(?:/(.*))?", loc)
    if match:
        level = int(match[1] or 0)
        base = f"the `{groups[level]}` item" if level < len(groups) else f"the item {level} groups out"
        return base + ("'s `" + match[2] + "`" if match[2] else "")
    return f"`{loc}`" if loc else "the input"


def _members(pattern, groups):
    """The values a group runs over, in words: the members of one container, or the values at a pattern."""
    if pattern.endswith("/*") and "*" not in pattern[:-2]:
        return f"each member of {_place(pattern[:-2], groups)}"
    match = re.fullmatch(r"(@[0-9]*)/(.*)", pattern)
    if match:
        return f"each value at `{match[2]}` under {_place(match[1], groups)}"
    return f"each value at `{pattern}`"


def _literal(literal, groups=()):
    op, arg = next(iter(literal.items()))
    loc = arg if op in ("present", "absent") else arg[0]
    where = _place(loc, groups)
    if op in ("present", "absent"):
        return f"{where} is {op}"
    if op in ("equals", "differs"):
        value = json.dumps(arg[1], ensure_ascii=False, separators=(",", ":"))
        return f"{where} is " + (value if op == "equals" else "absent or is not " + value)
    typ = _type_word(arg[1])
    return f"{where} is " + (typ if op == "is" else "absent or is not " + typ)


def _ids(entries):
    """The check and member ids of a list of entries, groups included, in table order."""
    out = []
    for entry in entries:
        if "each" in entry:
            out += _ids(entry["checks"])
        elif entry.get("kind") == "classifier":
            out += [m["id"] for m in entry["emits"]]
        elif entry.get("kind") != "include":
            out.append(entry["id"])
    return out


def _lead(groups):
    """The item a hand-written sentence inside groups reads, named: its `the item` is this one."""
    return ("For the " + " of the ".join(f"`{g}` item" for g in groups) + ": ") if groups else ""


def wording(entry, *, groups=(), limits=None):
    """The sentence specified in wire-contract.md 3.1, from one table row. `groups` are the ids of the
    enclosing groups, innermost first; a group's own sentence is read in the groups around it."""
    prefix = ("When " + " and ".join(_literal(x, groups) for x in entry["when"]) + ": "
              if entry.get("when") else "")
    def sentence_after(prefix, sentence):
        return prefix + (sentence[0].lower() + sentence[1:] if prefix and sentence.startswith("The ") else sentence)
    if "each" in entry:
        ids = _ids(entry["checks"])
        checks = (f"check `{ids[0]}` runs" if len(ids) == 1 else f"checks `{ids[0]}` and `{ids[1]}` run"
                  if len(ids) == 2 else f"checks `{ids[0]}` to `{ids[-1]}` run")
        guard = (", when " + " and ".join(_literal(x, groups) for x in entry["when"])) if entry.get("when") else ""
        return (f"Group `{entry['id']}`{guard}: its item is {_members(entry['each'], groups)}, in order; "
                f"{checks} on one item before the next item.")
    if entry.get("kind") == "include":
        names = ", ".join(f"`{n}`" for n in entry["phases"])
        sentence = (f"The checks of phase {names} of `{entry['contract']}`, in their order, "
                    f"on {_place(entry.get('at', '@' if groups else ''), groups)}")
        if "view" in entry:
            sentence += f" as transformed by the view `{entry['view']}`: {entry['says']}"
        else:
            sentence += "."
        if "as" in entry:
            sentence += f" They are reported with code `{entry['as']}`."
        return sentence_after(prefix, sentence)
    kind = entry["kind"]
    if kind == "hook":
        return prefix + _lead(groups) + entry.get("says", "")
    if kind == "classifier":
        return prefix + _lead(groups) + " ".join(m["says"] for m in entry["emits"])
    loc = entry.get("at", "@" if groups else "")
    w = _place(loc, groups)
    keys = lambda k: ", ".join(f"`{x}`" for x in entry[k])
    literal = lambda v: json.dumps(v, ensure_ascii=False, separators=(",", ":"))
    if kind == "type":
        sentence = f"{w}, when present, is {_type_word(entry['type'])}."
    elif kind == "exact_keys":
        sentence = f"{w}, when present, is an object with exactly the keys {keys('keys')}."
    elif kind == "keys":
        sentence = f"{w}, when present, is an object with the keys {keys('required')}"
        sentence += (f" and no other key except {keys('optional')}." if entry["optional"]
                     else " and no other key.")
    elif kind == "const":
        sentence = f"{w}, when present, is {literal(entry['value'])}."
    elif kind == "enum":
        sentence = f"{w}, when present, is one of {', '.join(map(literal, entry['values']))}."
    elif kind == "max_items":
        sentence = f"{w}, when it is an array or an object, has at most {_bound(entry['limit'], limits)} members."
    elif kind == "max_bytes":
        sentence = f"{w}, when it is a string, is at most {_bound(entry['limit'], limits)} bytes long in UTF-8."
    elif kind == "max_count":
        sentence = f"There are at most {_bound(entry['limit'], limits)} values at `{entry['of']}`."
    elif kind == "name":
        sentence = (f"The key of {w} is in the class `{entry['class']}`." if entry.get("on") == "key"
                    else f"{w}, when present, is a string in the class `{entry['class']}`.")
    elif kind == "sorted_unique":
        sentence = f"{w}, when it is an array of strings, is in strictly increasing code point order."
    elif kind == "unique_so_far":
        within = "".join(f" of the same `{g}` item" for g in groups[1:2])
        sentence = (f"{w}, when present, differs from the value at the same place in every earlier "
                    f"`{groups[0]}` item{within}.")
    elif kind == "declared_in":
        sentence = f"{w}, when present, equals one of the values at `{entry['set']}`."
    elif kind in ("requires", "excludes"):
        if "member" in entry:
            sentence = (f"{w}, when it is an object, has " + ("the key " if kind == "requires" else "no key ")
                        + f"`{entry['member']}`.")
        else:
            sentence = (f"{w}, when it is an array, " + ("contains " if kind == "requires" else "does not contain ")
                        + literal(entry["item"]) + ".")
    else:
        raise ValueError(kind)
    return sentence_after(prefix, sentence[0].upper() + sentence[1:])


def _bound(value, limits=None):
    if type(value) is int:
        return str(value)
    limits = limits or loads_json((DATA / "limits.json").read_bytes())
    return f"{limits[value]} ({value})"


def english_table(contract, *, limits=None):
    """The generated table: one row per check, member, group and include, in table order. A row inside a
    group is marked with one `·` per enclosing group, and a group's row names the checks it covers."""
    lines = ["<!-- GENERATED by tools/wire_contract.py; do not edit. -->",
             "| Check | Code | One reading |", "|---|---|---|"]
    def entries(rows, groups=()):
        mark = "· " * len(groups)
        for entry in rows:
            if "each" in entry:
                lines.append(f"| {mark}`{entry['id']}` | group | {wording(entry, groups=groups)} |")
                entries(entry["checks"], (entry["id"],) + groups)
            elif entry.get("kind") == "classifier":
                for member in entry["emits"]:
                    lines.append(f"| {mark}`{member['id']}` | `{member['code']}` | "
                                 f"{_lead(groups)}{member['says']} |")
            else:
                code = entry.get("code", entry.get("as", "include"))
                lines.append(f"| {mark}`{entry['id']}` | `{code}` | {wording(entry, groups=groups, limits=limits)} |")
    for index, phase in enumerate(contract["phases"], 1):
        lines.append(f"| **Phase {index}, {phase['name']}** | | No check of this phase runs unless every check of the earlier phases holds over the whole input. |")
        entries(phase["checks"])
    return "\n".join(lines) + "\n"


def _views_inside(contract, phases, known, seen=frozenset()):
    """The ids of includes with a view anywhere inside the named phases of a contract, following its own
    includes into the contracts they name (2.6: views do not nest)."""
    found = []
    def walk(entries):
        for entry in entries:
            if "each" in entry:
                walk(entry["checks"])
            elif entry.get("kind") == "include":
                if "view" in entry:
                    found.append(f"{contract['contract']}:{entry['id']}")
                target = known.get(entry.get("contract"))
                step = (entry.get("contract"), tuple(entry.get("phases", ())))
                if target is not None and step not in seen:
                    found.extend(_views_inside(target, entry.get("phases", ()), known, seen | {step}))
    for phase in contract["phases"]:
        if phase["name"] in phases:
            walk(phase["checks"])
    return found


def lint(contract, *, limits, names, known=None, catalogue=None):
    """Return (code, detail) findings; no fixture or legacy verdict is changed. `catalogue`, when given, is
    the set of checks and classifier members with a fault in the fault catalogue (8.3, the `WC08` clause)."""
    known = known or {}
    findings = []
    def issue(code, detail):
        findings.append((code, detail))
    required = {"contract", "revision", "format", "status", "input", "uses", "codes", "residual", "phases"}
    if (type(contract) is not dict or not required <= contract.keys() or
            contract.keys() - required - {"adapter"} or contract.get("format") != 1 or
            contract.get("status") not in ("shadow", "public") or
            type(contract.get("revision")) is not int or contract["revision"] < 1):
        return [("WC01", "invalid contract envelope")]
    codes = contract["codes"]
    if (type(limits) is not dict or any(type(value) is not int or value < 0
                                        for value in limits.values())):
        issue("WC05", "limits must be named non-negative integers")
    if type(names) is not dict:
        issue("WC05", "names must be an object")
        return findings
    for class_name, definition in names.items():
        allowed = {"first", "rest", "min_bytes", "max_bytes", "forbid_prefix", "forbid_infix", "enum"}
        if type(definition) is not dict or set(definition) - allowed:
            issue("WC05", f"invalid name class {class_name}")
            continue
        for bound in ("min_bytes", "max_bytes"):
            if bound in definition and (type(definition[bound]) is not int or definition[bound] < 0):
                issue("WC05", f"invalid {bound} in {class_name}")
        for char_set in ("first", "rest"):
            if char_set in definition:
                spec = definition[char_set]
                if (type(spec) is not str or not re.fullmatch(r"(?:[ -~](?:-[ -~])?)*", spec)
                        or any(a > b for a, b in re.findall(r"(.)-(.)", spec))):
                    issue("WC05", f"invalid character set in {class_name}")
        for strings in ("forbid_prefix", "forbid_infix", "enum"):
            if strings in definition and (type(definition[strings]) is not list or
                                           any(type(v) is not str for v in definition[strings])):
                issue("WC05", f"invalid {strings} in {class_name}")
    if type(codes) is not dict or any(type(v) is not dict or set(v) != {"class", "summary"}
                                      or v["class"] not in CLASSES for v in codes.values()):
        issue("WC03", "invalid code declaration")
        return findings
    used = {contract["residual"]}
    for value in (contract["contract"], contract.get("adapter", ""),
                  *(phase.get("name", "") for phase in contract["phases"]),
                  *(part for code, definition in codes.items()
                    for part in (code, definition["class"], definition["summary"]))):
        if FORBIDDEN.search(value):
            issue("WC07", f"forbidden Lean token in {value}")
    seen = set()
    ordered = []
    def pattern(loc, depth, *, wild=False):
        if type(loc) is not str or not (PATTERN if wild else LOCATION).fullmatch(loc):
            issue("WC06", f"invalid location {loc!r}")
            return
        match = re.match(r"@([0-9]*)", loc)
        if match and int(match[1] or 0) >= depth:
            issue("WC06", f"unbound item base {loc}")
    def guard(entry, depth):
        for literal in entry.get("when", []):
            if type(literal) is not dict or len(literal) != 1:
                issue("WC01", "invalid guard literal")
                continue
            op, arg = next(iter(literal.items()))
            if op not in {"present", "absent", "equals", "differs", "is", "is_not"}:
                issue("WC01", f"unknown guard {op}")
                continue
            loc = arg if op in ("present", "absent") else arg[0]
            pattern(loc, depth)
            if op in ("equals", "differs") and type(arg[1]) not in (str, int, bool):
                issue("WC06", "non-scalar literal")
    def template(entry):
        value = entry["text"]
        if type(value) is not str or not value.isascii():
            issue("WC04", "non-ASCII template")
            return
        try:
            found = [p[1:] for p in split_template(value) if p[0] == "arg"]
        except ValueError:
            issue("WC04", f"unbalanced template {entry['id']}")
            return
        allowed = {"value", "key", "index", "count", "limit"} | set(entry.get("args", {})) | set(entry.get("returns", []))
        renderers = {}
        for name, renderer in found:
            if name not in allowed or renderer not in RENDERERS or (name in renderers and renderers[name] != renderer):
                issue("WC04", f"invalid placeholder {entry['id']}:{name}")
            renderers[name] = renderer
        if (set(entry.get("args", {})) | set(entry.get("returns", []))) - renderers.keys():
            issue("WC04", f"unused argument {entry['id']}")
    def walk(entries, depth=0):
        for entry in entries:
            if type(entry) is not dict or "id" not in entry:
                issue("WC01", "invalid entry")
                continue
            eid = entry["id"]
            if type(eid) is not str or not ID.fullmatch(eid) or eid == "residual" or eid in seen:
                issue("WC02", f"invalid or repeated id {eid}")
            seen.add(eid)
            guard(entry, depth)
            if "each" in entry:
                if set(entry) - {"id", "each", "when", "checks"} or type(entry.get("checks")) is not list:
                    issue("WC01", f"invalid group shape {eid}")
                pattern(entry["each"], depth, wild=True)
                walk(entry["checks"], depth + 1)
                continue
            kind = entry.get("kind")
            if kind == "include":
                if set(entry) - {"id", "kind", "contract", "phases", "at", "view", "says", "as"} or not {"contract", "phases"} <= set(entry):
                    issue("WC01", f"invalid include shape {eid}")
                if ("view" in entry) != ("says" in entry):
                    issue("WC08" if "view" in entry else "WC01", f"include says/view mismatch {eid}")
                target = known.get(entry.get("contract"))
                if target is None or entry["contract"] not in contract["uses"]:
                    issue("WC09", f"unknown include {eid}")
                elif not set(entry["phases"]) <= {p["name"] for p in target["phases"]}:
                    issue("WC09", f"unknown phase {eid}")
                else:
                    for inner in _views_inside(target, entry["phases"], known):
                        issue("WC09", f"include with a view {inner} inside the phases included by {eid}")
                if "as" in entry:
                    used.add(entry["as"])
                for value in (entry.get("contract", ""), entry.get("view", ""),
                              entry.get("says", ""), entry.get("as", "")):
                    if FORBIDDEN.search(value):
                        issue("WC07", f"forbidden Lean token {eid}")
                pattern(entry.get("at", "@" if depth else ""), depth)
                continue
            if kind == "classifier":
                members = entry.get("emits", [])
            elif kind in T1 | {"hook"}:
                members = [entry]
            else:
                issue("WC01", f"unknown kind {kind}")
                continue
            required_fields = {"id", "kind"} | PARAMS[kind]
            if kind != "classifier":
                required_fields |= {"code", "text"}
            optional_fields = CHECK_COMMON | PARAMS[kind]
            if kind == "name":
                optional_fields |= {"on"}
            if kind in ("requires", "excludes"):
                optional_fields |= {"member", "item"}
            if kind == "hook":
                optional_fields |= {"returns", "inherited"}
            if kind == "classifier":
                optional_fields -= {"code", "text", "args", "says"}
            if not required_fields <= set(entry) or set(entry) - optional_fields:
                issue("WC01", f"invalid {kind} shape {eid}")
            if kind in ("requires", "excludes") and ("member" in entry) == ("item" in entry):
                issue("WC01", f"{kind} needs exactly one member or item {eid}")
            for member in members:
                mid = member["id"]
                if member is not entry:
                    if mid in seen or not ID.fullmatch(mid):
                        issue("WC02", f"invalid or repeated member {mid}")
                    seen.add(mid)
                if ordered and (not _comparable(ordered[-1], mid) or _id_key(ordered[-1]) >= _id_key(mid)):
                    issue("WC02", f"out-of-order check {mid}")
                ordered.append(mid)
                used.add(member["code"])
                template(member)
                if (kind == "hook" or member is not entry) and not member.get("says"):
                    issue("WC08", f"missing says {mid}")
                if (kind == "hook" or member is not entry) and catalogue is not None and mid not in catalogue:
                    issue("WC08", f"no fault in the fault catalogue for {mid}")
                if member.get("inherited") and (member.get("returns") != ["message"] or member["text"] != "{message}"):
                    issue("WC08", f"invalid inherited text {mid}")
                for value in (mid, member["code"], member["text"], member.get("says", "")):
                    if FORBIDDEN.search(value):
                        issue("WC07", f"forbidden Lean token {mid}")
            if kind == "classifier":
                if FORBIDDEN.search(entry["classifier"]):
                    issue("WC07", f"forbidden Lean token {eid}")
                continue
            if kind == "hook" and FORBIDDEN.search(entry["hook"]):
                issue("WC07", f"forbidden Lean token {eid}")
            loc = entry.get("at", "@" if depth else "")
            pattern(loc, depth)
            for arg in entry.get("args", {}).values():
                pattern(arg, depth)
            if kind == "unique_so_far" and (not depth or not loc.startswith("@")):
                issue("WC06", f"unique_so_far needs a group {eid}")
            if kind == "name":
                if entry.get("class") not in names:
                    issue("WC05", f"unknown name class {eid}")
                if entry.get("on") == "key" and loc == "":
                    issue("WC06", f"key check at root {eid}")
            if kind in ("max_items", "max_bytes", "max_count") and type(entry["limit"]) is str and entry["limit"] not in limits:
                issue("WC05", f"unknown limit {eid}")
            if kind in ("max_count", "declared_in"):
                pattern(entry["of"] if kind == "max_count" else entry["set"], depth, wild=True)
    for phase in contract["phases"]:
        walk(phase["checks"])
    if used != set(codes):
        issue("WC03", f"code declarations differ from uses: {sorted(used ^ set(codes))}")
    return findings


def default_catalogue(directory):
    """The checks with a fault in the fault catalogue (8.3), per contract: the index of each shipped unit's
    catalogue (`conformance/wire_contract_faults.py` dispatches to it, kept current by a test) for the shipped
    contracts, and the hand-derived records of the engine corpus for the corpus contracts."""
    if directory.resolve() == DATA.resolve():
        found = {}
        for unit in UNITS:
            index = ROOT / unit_paths(unit)["catalogue"]
            if index.exists():
                value = json.loads(index.read_text())
                found[value["contract"]] = set(value["faults"]) | set(value["unreached"])
        return found
    golden = directory.parent / "engine-golden.json"
    if not golden.exists():
        return None
    records = json.loads(golden.read_text())
    return {unit: {r["check"] for r in cases.values() if type(r) is dict and "check" in r}
            for unit, cases in records.items() if unit.endswith("@0") and type(cases) is dict}


def _through_includes(catalogue, contracts):
    """A check whose fault only an including unit's catalogue holds, as `<include id>/<check>`, has a fault
    for the included contract too (wire-contract-s5.md 4.4: gap G3 of 8.4)."""
    result = {unit: set(checks) for unit, checks in catalogue.items()}
    for unit, checks in catalogue.items():
        sites = {}
        def walk(entries):
            for entry in entries:
                if "each" in entry:
                    walk(entry["checks"])
                elif entry.get("kind") == "include":
                    sites[entry["id"]] = entry["contract"]
        for phase in contracts.get(unit, {}).get("phases", []):
            walk(phase["checks"])
        for check in checks:
            head, _, rest = check.partition("/")
            if rest and head in sites:
                result.setdefault(sites[head], set()).add(rest)
    return result


def _check_unit(unit, contracts, directory, limits, names, write, findings, issue,
                generated_only=False):
    """The checks of one shipped unit (7.1): every hook, classifier, view and adapter its table names is in
    its registry, its examples are accepted by its legacy validation and found clean by the engine, and its
    English table is the generated one."""
    module, (legacy_module, legacy_name) = UNITS[unit]
    registry = importlib.import_module(module).REGISTRY
    legacy = None if generated_only else getattr(importlib.import_module(legacy_module), legacy_name)
    path = directory / f"{unit}.json"
    def registered(entries):
        for entry in entries:
            if "each" in entry:
                registered(entry["checks"])
            elif entry["kind"] == "hook" and entry["hook"] not in registry.hooks:
                issue(path, "WC08", f"unregistered hook {entry['hook']}")
            elif entry["kind"] == "classifier" and entry["classifier"] not in registry.classifiers:
                issue(path, "WC08", f"unregistered classifier {entry['classifier']}")
            elif entry["kind"] == "include" and "view" in entry and entry["view"] not in registry.views:
                issue(path, "WC08", f"unregistered view {entry['view']}")
    for phase in contracts[unit]["phases"]:
        registered(phase["checks"])
    if contracts[unit].get("adapter") not in registry.adapters:
        issue(path, "WC08", "unregistered adapter")
    examples = sorted((directory / "examples" / unit).glob("*.json"))
    if len(examples) < 2:
        issue(directory / "examples" / unit, "WC10", "fewer than two examples")
    for example in (() if generated_only else examples):
        try:
            root = loads_json(example.read_bytes())
            if legacy is not None:
                legacy(root["environment"], root["norms"])
            if run(contracts[unit], root, registry=registry, contracts=contracts,
                   limits=limits, names=names) is not CLEAN:
                issue(example, "WC10", "engine does not report clean")
        except Exception as exc:
            issue(example, "WC10", f"example is not accepted: {exc}")
    generated = english_table(contracts[unit], limits=limits)
    target = ROOT / unit_paths(unit)["english"]
    if write and not findings:
        target.write_text(generated)
    elif not write and (not target.exists() or target.read_text() != generated):
        issue(target, "WC11", "generated English table differs")


def process(directory=DATA, *, write=False, catalogue=None, generated_only=False):
    """Lint, lock and regenerate (4.3). `catalogue` maps a contract to the checks with a catalogue fault;
    by default it is `default_catalogue(directory)`, and a contract it does not name has none."""
    findings = []
    if catalogue is None:
        catalogue = default_catalogue(directory)
    def issue(path, code, detail):
        findings.append(f"{path}: {code}: {detail}")
    try:
        limits = loads_json((directory / "limits.json").read_bytes())
        names = loads_json((directory / "names.json").read_bytes())
        lock_path = directory / "contracts.lock"
        lock = loads_json(lock_path.read_bytes()) if lock_path.exists() else {}
    except Exception as exc:
        return [f"{directory}: WC01: {exc}"]
    files = [directory / "limits.json", directory / "names.json"] + sorted(directory.glob("*@*.json"))
    contracts = {}
    for path in files[2:]:
        try:
            value = loads_json(path.read_bytes())
            contracts[value["contract"]] = value
        except Exception as exc:
            issue(path, "WC01", str(exc))
    def dependencies(entries):
        result = set()
        for entry in entries:
            if "each" in entry:
                result.update(dependencies(entry["checks"]))
            elif entry.get("kind") == "include":
                result.add(entry["contract"])
        return result
    graph = {unit: set().union(*(dependencies(phase["checks"]) for phase in value["phases"]))
             for unit, value in contracts.items()}
    def cycle(start, current, seen):
        return any(target == start or (target not in seen and cycle(start, target, seen | {target}))
                   for target in graph.get(current, ()))
    for unit in graph:
        if cycle(unit, unit, {unit}):
            issue(directory / f"{unit}.json", "WC09", "include cycle")
    if catalogue is not None:
        catalogue = _through_includes(catalogue, contracts)
    for path in files:
        try:
            value = loads_json(path.read_bytes())
        except Exception:
            continue
        if path in files[2:]:
            try:
                checks = None if catalogue is None else catalogue.get(value.get("contract"), set())
                for code, detail in lint(value, limits=limits, names=names, known=contracts, catalogue=checks):
                    issue(path, code, detail)
            except (KeyError, IndexError, TypeError, ValueError) as exc:
                issue(path, "WC01", f"invalid contract shape: {exc}")
        old = lock.get(path.name)
        revision = value.get("revision")
        if revision is None:
            revision = (old["revision"] + 1 if write and old and old["sha256"] != _hash(value)
                        else old["revision"] if old else 1)
        wanted = {"revision": revision, "sha256": _hash(value)}
        if write:
            if old and old["sha256"] != wanted["sha256"] and old["revision"] >= revision:
                issue(path, "WC10", "changed content needs a higher revision")
            else:
                lock[path.name] = wanted
        elif lock.get(path.name) != wanted:
            issue(path, "WC10", "lock hash or revision differs")
    shipped = [unit for unit in UNITS if unit in contracts] if directory.resolve() == DATA.resolve() else []
    for unit in contracts if directory.resolve() == DATA.resolve() else ():
        if unit not in UNITS:
            issue(directory / f"{unit}.json", "WC08", "no registry for the unit in tools/wire_contract.py")
    for unit in shipped:
        _check_unit(unit, contracts, directory, limits, names, write, findings, issue,
                    generated_only=generated_only)
    if shipped and not findings:
        rendered = generated_lean(contracts, limits, names)
        inventory = ROOT / "lean/VE/Route/frozen-sources.sha256"
        inventory_lines = inventory.read_text().splitlines()
        inventory_map = {line.split("  ", 1)[1]: line.split("  ", 1)[0]
                         for line in inventory_lines if "  " in line}
        for relative, source in rendered.items():
            target = ROOT / relative
            inventory_key = relative.removeprefix("lean/")
            digest = hashlib.sha256(source.encode()).hexdigest()
            if write:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(source)
                inventory_map[inventory_key] = digest
            else:
                if not target.exists() or target.read_text() != source:
                    issue(target, "WC11", "generated Lean module differs")
                if inventory_map.get(inventory_key) != digest:
                    issue(inventory, "WC11", f"generated module hash differs: {inventory_key}")
        if write:
            inventory.write_text("".join(f"{digest}  {path}\n"
                                         for path, digest in sorted(inventory_map.items())))
    if write and not findings:
        lock_path.write_bytes(canonical_json(lock) + b"\n")
    return findings


def main():
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    parser.add_argument("--generated-only", action="store_true",
                        help="check generated tables without live validation (staged snapshots)")
    parser.add_argument("--directory", type=Path, default=DATA)
    args = parser.parse_args()
    findings = process(args.directory, write=args.write, generated_only=args.generated_only)
    for line in findings:
        print(line)
    return bool(findings)


if __name__ == "__main__":
    sys.exit(main())
