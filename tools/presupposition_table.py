"""Write or check `lean/VE/Presupposition/Table.lean`, PS-E1's candidate table as Lean's `candidateTable`.

    python tools/presupposition_table.py --write
    python tools/presupposition_table.py --check

The table is `docs/research/presupposition-E1/candidate-table.json` (presupposition spec section 6): one object per
row, `{"row": ..., "cells": {<class>: [<candidate>, ...]}}`, candidates in the measured order. The JSON owns the
values; this script only spells them in Lean, one `match` arm per non-empty cell, in the file's row order and the
spec's class order. Lean checks the shape (`#guard tableOk rowNames candidateTable` in Examples.lean). A name that
is not a spec class or candidate, a missing or extra class, or a repeated row is refused. `--check` fails when the
file differs from its rendering.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/research/presupposition-E1/candidate-table.json"
TARGET = ROOT / "lean/VE/Presupposition/Table.lean"

CLASSES = {"top": "top", "negated": "negated", "antecedent": "antecedent", "consequent": "consequent",
           "disjunct": "disjunct", "rule_act": "ruleAct", "rule_guard": "ruleGuard"}
CANDIDATES = {"assumed": "assumed", "conditioned": "conditioned", "asserted": "asserted", "in_place": "inPlace",
              "unconditional": "unconditional"}

HEADER = '''import VE.Presupposition.Wire

/-! PS-E1's candidate table (docs/research/presupposition-E1/candidate-table.json, presupposition spec section 6).
Generated by `python3 tools/presupposition_table.py --write`; do not edit. -/

namespace VE.Presupposition

/-- PS-E1's table: the candidates of each row and position class, in the measured order; an empty cell and a row
    PS-E1 did not measure list none. -/
def candidateTable : CandidateTable := fun row pc => match row, pc with
'''


def arms(rows: list) -> list[str]:
    """One `match` arm per non-empty cell; refuses names outside the spec's classes and candidates."""
    out, seen = [], set()
    for entry in rows:
        row, cells = entry["row"], entry["cells"]
        if row in seen or set(cells) != set(CLASSES):
            raise ValueError(f"row {row!r}: repeated, or classes {sorted(cells)} are not {sorted(CLASSES)}")
        seen.add(row)
        for name, lean in CLASSES.items():
            if cells[name]:
                cands = ", ".join("." + CANDIDATES[c] for c in cells[name])  # KeyError: an unknown candidate
                out.append(f"  | {json.dumps(row)}, .{lean} => [{cands}]")
    return out


def render(rows: list | None = None) -> str:
    rows = json.loads(SOURCE.read_text()) if rows is None else rows
    return HEADER + "\n".join(arms(rows) + ["  | _, _ => []", "", "end VE.Presupposition", ""])


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        TARGET.write_text(text)
        return 0
    if not TARGET.exists() or TARGET.read_text() != text:
        print(f"{TARGET.relative_to(ROOT)} differs from PS-E1's table; run --write")
        return 1
    print("PASS: candidateTable is PS-E1's table")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
