use serde_json::json;
use ve_core::{Environment, FiniteModel};

#[test]
fn regulated_environment_and_profile_model() {
    let env_data = json!({
        "language": "ve.core@0.2",
        "profiles": ["norms@0", "relational-fol@0"],
        "spec_revision": "ve-v0.2-expand2-2026-09-25",
        "vocabulary": {
            "sorts": {"act": {"description": "act"}},
            "predicates": {
                "required": {"arguments": ["act"], "description": "required",
                    "regulated": {"role": "obligation", "default": "deny",
                                  "act": "{0} be done", "permission": "permitted"}},
                "permitted": {"arguments": ["act"], "description": "permitted",
                    "regulated": {"role": "permission", "default": "deny",
                                  "act": "{0} be done"}}
            },
            "constants": {}
        }
    });
    let env = Environment::from_value(&env_data).unwrap();
    // Independently generated by Python Environment for this exact declaration.
    assert_eq!(env.environment_id(),
               "e4b81eb44a51fa37c66bc73c651fb87935eea658ed00c9e472c58e55b0b33224");
    let bad = json!({"complete": true, "domains": {"act": ["a"]},
                     "constants": {}, "relations": {"required": [["a"]], "permitted": []}});
    assert_eq!(FiniteModel::from_value(&env, &bad).unwrap_err().code, "InvalidModel");
    let good = json!({"complete": true, "domains": {"act": ["a"]},
                      "constants": {}, "relations": {"required": [["a"]], "permitted": [["a"]]}});
    assert!(FiniteModel::from_value(&env, &good).is_ok());
    let mut missing_dual = env_data.clone();
    missing_dual["vocabulary"]["predicates"]["required"]["regulated"]
        .as_object_mut().unwrap().remove("permission");
    assert!(Environment::from_value(&missing_dual).unwrap_err().message.contains("MissingPermissionDual"));
}

#[test]
fn act_phrase_whitespace_matches_python_split() {
    // Python `str.split()` separators, including U+001C..U+001F, which
    // `char::is_whitespace` does not include.
    let env = |act: &str| json!({
        "language": "ve.core@0.2",
        "profiles": ["norms@0", "relational-fol@0"],
        "spec_revision": "ve-v0.2-expand2-2026-09-25",
        "vocabulary": {
            "sorts": {"act": {"description": "act"}},
            "predicates": {"permitted": {"arguments": ["act"], "description": "permitted",
                "regulated": {"role": "permission", "default": "deny", "act": act}}},
            "constants": {}
        }
    });
    let plain = Environment::from_value(&env("{0} be done")).unwrap();
    for sep in ["\t", "\n", "\u{0b}", "\u{0c}", "\r", "\u{1c}", "\u{1d}", "\u{1e}", "\u{1f}",
                "\u{85}", "\u{a0}", "\u{1680}", "\u{2000}", "\u{200a}", "\u{2028}", "\u{2029}",
                "\u{202f}", "\u{205f}", "\u{3000}"] {
        let spaced = Environment::from_value(&env(&format!("{{0}}{sep}be{sep}{sep}done"))).unwrap();
        assert_eq!(spaced.environment_id(), plain.environment_id(), "{sep:?}");
    }
    // Not a Python separator: zero-width space stays inside the word.
    assert!(Environment::from_value(&env("{0}\u{200b}be done")).is_err());
}

#[test]
fn regulated_predicate_cannot_be_defined_or_flagged() {
    let mut env = json!({
        "language": "ve.core@0.2",
        "profiles": ["data@0", "definitions@0", "norms@0", "relational-fol@0"],
        "spec_revision": "ve-v0.2-expand2-2026-09-25",
        "vocabulary": {
            "sorts": {"act": {"description": "act"}},
            "predicates": {"permitted": {"arguments": ["act"], "description": "permission",
                "regulated": {"role": "permission", "default": "deny", "act": "{0} be done"}}},
            "constants": {}
        }
    });
    let predicate = &mut env["vocabulary"]["predicates"]["permitted"];
    predicate["defined"] = json!({"arguments": ["act"], "body": ["top"]});
    assert!(Environment::from_value(&env).unwrap_err().message.contains("RegulatedDefinedPredicate"));
    env["vocabulary"]["predicates"]["permitted"]
        .as_object_mut().unwrap().remove("defined");
    env["vocabulary"]["predicates"]["permitted"]["functional"] = json!(false);
    assert!(Environment::from_value(&env).unwrap_err().message.contains("RegulatedFlag"));
}
