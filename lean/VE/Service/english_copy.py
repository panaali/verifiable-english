"""Generate or check VE/Service/EnglishRun.lean, the service's copy of the English runner.

Usage (from lean/): python3 VE/Service/english_copy.py [--check]

`VE/English/Run.lean` declares a root-level `main` (it is run with `lake env lean --run`
and as the `ve_english_run` executable), so `ve_service`, which has its own `main`,
cannot import it, and the frozen source may not be edited. The copy is the original
text with the namespace `VE.English.Run` renamed `VE.English.ServiceRun` and the root
`main` omitted. Both namespaces sit inside `VE.English`, so every identifier resolves
exactly as in the original. `--check` exits 1 if the committed copy differs from what
this script generates, which pins the copy to the original byte for byte.
"""
from pathlib import Path
import sys

LEAN = Path(__file__).resolve().parents[2]
ORIGINAL = LEAN / "VE/English/Run.lean"
COPY = LEAN / "VE/Service/EnglishRun.lean"
END = "\nend VE.English.Run\n"
HEADER = """\
/- GENERATED by VE/Service/english_copy.py from VE/English/Run.lean; do not edit.
The original declares a root `main`, so the service executable cannot import it.
This is its text with the namespace renamed `VE.English.ServiceRun` (the same
enclosing namespace, so every name resolves as in the original) and the root
`main` omitted. `python3 VE/Service/english_copy.py --check` fails on any drift. -/
"""


def generate():
    text = ORIGINAL.read_text()
    assert text.count(END) == 1 and text.count("namespace VE.English.Run\n") == 1
    body = text[:text.index(END) + len(END)]
    assert "def main" not in body
    body = body.replace("namespace VE.English.Run\n", "namespace VE.English.ServiceRun\n")
    body = body.replace(END, "\nend VE.English.ServiceRun\n")
    assert "VE.English.Run" not in body.split("-/", 1)[1]
    return HEADER + body


def main(argv):
    expected = generate()
    if argv == ["--check"]:
        if not COPY.exists() or COPY.read_text() != expected:
            print(f"CHANGED: {COPY.relative_to(LEAN)} differs from the generated copy of {ORIGINAL.relative_to(LEAN)}")
            return 1
        print("PASS: VE/Service/EnglishRun.lean is the generated copy of VE/English/Run.lean")
        return 0
    COPY.write_text(expected)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
