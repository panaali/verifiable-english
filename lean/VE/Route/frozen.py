"""Hash test for the narrow freeze (architecture decision D2).

Usage (from lean/): python3 VE/Route/frozen.py        exits 0 iff unchanged.
                    python3 VE/Route/frozen.py --write regenerates the inventory from the tree (after a
                    reviewed edit of a frozen file or a merge; tools/regen_generated.py runs it);
                    `Main.lean` is still only checked.
`frozen-sources.sha256` hashes only the files D2 keeps frozen: every module holding a K declaration
(kernel definitions, class `K` in the trust map's side table `tools/trust-classes.json`) and the
frozen-contract decoders that define the `ve.core@0.1` identities (`DECODERS`). Every other module is
not hashed here: its statements and meaning predicates are in `statements.txt` and `predicates.txt`,
its compiled source hash in `declarations.txt`, and `tools/trust_changes.py --since BASE` lists the
changed D[V] and G[V] files by trust-map class. A new module needs no line unless it holds a K
declaration. `Main.lean` with the two route lines removed must hash to the base file.
"""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
INVENTORY = "VE/Route/frozen-sources.sha256"
TABLE = "../tools/trust-classes.json"
MAIN_BASE = "1bd244f8ff087d3f81e7302a0938ceab9d107e9efd609d97e41b23c0eb36c26d"
ROUTE_LINES = ("import VE.Route.Run\n",
               '  if let "route" :: rest := args then return ← VE.Route.Run.main rest\n')
# The frozen-contract decoders: the files whose definitions are the `ve.core@0.1` identities. SHA-256,
# the restricted canonical JSON and the `ve-environment-v0`/`v0.1` and `ve-meaning-` digests; the JSON
# reader whose values those digests hash; the `v0.1-order` identities of the order profile.
DECODERS = ("VE/CertificateWire.lean", "VE/Json.lean", "VE/Order/Wire.lean")
HEADER = ("# Generated by `python3 VE/Route/frozen.py --write` (from lean/); do not edit. The hash-frozen files\n"
          "# of decision D2: modules with K declarations (tools/trust-classes.json) and the ve.core@0.1 decoders.\n")


def frozen_names(table: str) -> list[str]:
    """The hash-frozen files, by path from `lean/`: the modules of the side table `table` (its text) with a
    K entry, and the frozen-contract decoders."""
    kernel = {module for module, classes in json.loads(table)["modules"].items() if classes.get("K")}
    return sorted(kernel | set(DECODERS))


def recorded(text: str) -> dict[str, str]:
    """The inventory's `<sha256>  <path>` lines as a path-to-hash map; `#` lines are its header."""
    lines = [line for line in text.splitlines() if line.strip() and not line.startswith("#")]
    return {name: expected for expected, name in (line.split(maxsplit=1) for line in lines)}


def render(names: list[str], read) -> str:
    """The inventory of `names`, each hashed from `read(name)` (its bytes, or None when it is missing)."""
    rows = []
    for name in names:
        blob = read(name)
        rows.append(f"{'missing' if blob is None else hashlib.sha256(blob).hexdigest()}  {name}\n")
    return HEADER + "".join(rows)


def problems(inventory: str, table: str, read, main: str | None, only: set[str] | None = None) -> list[str]:
    """Every way the tree differs from the inventory. `read(name)` gives a file's bytes (None when missing),
    `main` the text of `Main.lean` (None to skip its rule). With `only`, just those paths' hashes are checked
    (the pre-commit hook's staged files); the listed set is then taken as given."""
    listed = recorded(inventory)
    bad = []
    for name in sorted(listed if only is None else listed.keys() & only):
        blob = read(name)
        if blob is None:
            bad.append(f"{name}: frozen file deleted but still listed")
        elif hashlib.sha256(blob).hexdigest() != listed[name]:
            bad.append(f"{name}: frozen file changed without an inventory update")
    if only is None:
        wanted = set(frozen_names(table))
        for name in sorted(wanted - listed.keys()):
            bad.append(f"{name}: frozen file (K declarations or a ve.core@0.1 decoder) is not listed")
        for name in sorted(listed.keys() - wanted):
            bad.append(f"{name}: listed but neither holds a K declaration nor is a ve.core@0.1 decoder")
        if inventory != render(sorted(listed), read) and not bad:
            bad.append(f"{INVENTORY}: not in the form `--write` writes")
    if main is not None:
        for route_line in ROUTE_LINES:
            if main.count(route_line) != 1:
                bad.append(f"Main.lean: expected exactly one {route_line.strip()!r}")
            main = main.replace(route_line, "")
        if hashlib.sha256(main.encode()).hexdigest() != MAIN_BASE:
            bad.append("Main.lean: existing subcommands changed")
    return bad


def read_tree(name: str) -> bytes | None:
    path = ROOT / name
    return path.read_bytes() if path.is_file() else None


def inventory_text() -> str:
    """The inventory of the tree as it is: what `--write` writes."""
    return render(frozen_names((ROOT / TABLE).read_text()), read_tree)


def main(argv=()):
    if list(argv) == ["--write"]:
        (ROOT / INVENTORY).write_text(inventory_text())
    elif list(argv):
        raise SystemExit("usage: python3 VE/Route/frozen.py [--write]")
    bad = problems((ROOT / INVENTORY).read_text(), (ROOT / TABLE).read_text(), read_tree,
                   (ROOT / "Main.lean").read_text())
    if bad:
        print("CHANGED:", *bad, sep="\n  ")
        return 1
    print("PASS: frozen Lean sources and Main.lean subcommands unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
