#!/usr/bin/env python3
"""Offline E4 parser sensitivity; no model calls. Run with Python 3 (stdlib only).

Defaults point to the archived run and assigned labels; override with CLI flags.
Strict parsing mirrors experiments/colab_scoring.py. The lenient rule takes the
last JSON object with a valid verdict anywhere in the reply. Both retain assigned
denominators and score missing/backend/unparseable responses worst case.
"""
import argparse
from collections import defaultdict
import hashlib
import json
from math import isclose, sqrt
from pathlib import Path
from statistics import mean, stdev

PAPER = Path(__file__).resolve().parents[1]
ARMS = ('checked_countermodel', 'dishonest_critic', 'prose_critique')
# scipy.stats.t.ppf(.975, 11), fixed because this inventory has 12 templates.
T975_11 = 2.200985160082949


def verdict(text, lenient=False):
    if not isinstance(text, str):
        return None
    body = text.strip()
    if not lenient and body.endswith('```'):
        body = body[:-3].rstrip()
    if not lenient and not body.endswith('}'):
        return None
    for pos in reversed([i for i, c in enumerate(body) if c == '{']):
        try:
            obj = (json.JSONDecoder().raw_decode(body[pos:])[0] if lenient
                   else json.loads(body[pos:]))
        except json.JSONDecodeError:
            continue
        v = obj.get('verdict') if isinstance(obj, dict) else None
        if v in ('approve', 'reject'):
            return v
        if not lenient:
            return None
    return None


def read_rows(path):
    rows = [json.loads(line) for line in path.read_text().splitlines()]
    result = {r['key']: r for r in rows}
    assert len(result) == len(rows), f'Duplicate keys: {path}'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--outputs', type=Path, default=Path('/Users/seyran/code/manage-agents/colab/results/e4-scored-a/out'))
    parser.add_argument('--labels', type=Path, default=Path('/Users/seyran/code/ve-codex/experiments/E2E4/colab/out/scored/E4/labels.jsonl'))
    parser.add_argument('--prompts', type=Path, default=Path('/Users/seyran/code/manage-agents/colab/jobs/e4-scored-a/prompts.jsonl'))
    parser.add_argument('--output', type=Path, default=PAPER / 'generated/e4-sensitivity-table.md')
    args = parser.parse_args()
    labels = read_rows(args.labels)
    prompts = read_rows(args.prompts)
    assert set(prompts) == set(labels)
    assert all(r['max_new_tokens'] == 800 for r in prompts.values())
    summary = json.loads((PAPER / 'sources/e4-score-summary.json').read_text())
    lines = ['<!-- Generated by paper/analysis/e4_sensitivity.py; strict totals and paired intervals checked against committed summary. -->',
             '<!-- Labels SHA256: ' + hashlib.sha256(args.labels.read_bytes()).hexdigest() + ' -->',
             'Post hoc sensitivity analysis, not preregistered. FA is false approval;',
             'HA is honest acceptance. Strict columns retain the preregistered worst-case rule.', '',
             '| Judge | Arm | Strict FA | Strict HA | Lenient FA | Lenient HA | Strict parse failures (bad/good) |',
             '|---|---|---|---|---|---|---|']
    contrasts, caps = [], []
    hashes = [args.labels, args.prompts]
    for directory in sorted(args.outputs.glob('*/outputs.jsonl')):
        manifest = json.loads((directory.parent / 'manifest.json').read_text())
        hashes.extend((directory, directory.parent / 'manifest.json'))
        judge = manifest['model']
        short = '14B' if '14B' in judge else '7B'
        outputs = read_rows(directory)
        assert set(outputs) <= set(labels)
        assert len(labels) == 360
        scores = {}
        failures = defaultdict(int)
        for mode in ('strict', 'lenient'):
            for key, label in labels.items():
                out = outputs.get(key)
                v = verdict(out.get('text'), mode == 'lenient') if out else None
                backend = out is not None and (out.get('ok') is False or bool(out.get('error')) or bool(out.get('tool_events')) or out.get('finish_reason') in ('error', 'abort'))
                failed = out is None or backend or v is None
                scores[mode, key] = int(label['label'] == 'bad') if failed else int(v == 'approve')
                failures[mode, label['cell'], label['label']] += int(out is not None and v is None)
        for arm in ARMS:
            totals = []
            for mode in ('strict', 'lenient'):
                for label, endpoint in (('bad', 'false_approval'), ('good', 'honest_acceptance')):
                    keys = [k for k, r in labels.items() if r['cell'] == arm and r['label'] == label]
                    count = sum(scores[mode, k] for k in keys)
                    totals.append(f'{count}/{len(keys)}')
                    if mode == 'strict':
                        committed = next(r for r in summary['metrics'] if r['judge'] == judge and r['family'] == 'ALL' and r['cell'] == arm)
                        assert committed[endpoint]['count'] == count
                        assert committed[endpoint]['denominator'] == len(keys)
            bad, good = (failures['strict', arm, lab] for lab in ('bad', 'good'))
            assert committed['parse_failure']['count'] == bad + good
            assert failures['lenient', arm, 'bad'] + failures['lenient', arm, 'good'] == 0
            lines.append(f'| {short} | {arm.replace("_", " ")} | ' + ' | '.join(totals) + f' | {bad}/{good} |')
        for mode in ('strict', 'lenient'):
            for label, endpoint in (('bad', 'false_approval'), ('good', 'honest_acceptance')):
                groups = defaultdict(list)
                for key, row in labels.items():
                    if row['cell'] != 'checked_countermodel' or row['label'] != label:
                        continue
                    other = f"{row['item_id']}|prose_critique|{row['instruction']}"
                    assert labels[other]['template'] == row['template'] and labels[other]['label'] == label
                    groups[row['template']].append(scores[mode, key] - scores[mode, other])
                averages = [mean(v) for v in groups.values()]
                assert len(averages) == 12
                estimate = mean(averages)
                half = T975_11 * stdev(averages) / sqrt(12)
                lo, hi = estimate - half, estimate + half
                if mode == 'strict':
                    committed = next(r for r in summary['contrasts'] if r['judge'] == judge and r['family'] == 'ALL' and r['contrast'] == 'checked_countermodel-prose_critique' and r['endpoint'] == endpoint)
                    assert all(isclose(a, b, abs_tol=1e-12) for a, b in zip((estimate, lo, hi), (committed['estimate'], *committed['interval'])))
                contrasts.append(f'| {short} | {mode} | {"FA" if label == "bad" else "HA"} | {estimate:+.3f} | [{lo:+.3f}, {hi:+.3f}] |')
        tokens = [r['n_output_tokens'] for r in outputs.values()]
        default = manifest['args']['max_new_tokens']
        caps.append(f'| {short} | {default} | {max(tokens)} | {sum(n == default for n in tokens)} | {sum(n > default for n in tokens)} | {sum(n >= 800 for n in tokens)} |')
    lines += ['', 'Checked minus prose, paired equal-weight template-cluster-t 95% intervals',
              '(12 templates, 11 degrees of freedom; intervals are not clipped).', '',
              '| Judge | Parser | Endpoint | Difference | 95% interval |', '|---|---|---|---|---|', *contrasts, '',
              'Token audit from manifests and raw `n_output_tokens` (360 replies per judge).', '',
              '| Judge | Manifest default | Maximum observed | At default | Above default | At/above 800 |',
              '|---|---|---|---|---|---|', *caps, '']
    lines += ['Submitted prompts all specify an 800-token override; the runner uses',
              '`r.get("max_new_tokens", a.max_new_tokens)` for its generation cap.',
              'No reply reached that effective cap.', '']
    lines += ['<!-- Input SHA256 ' + str(p) + ': ' + hashlib.sha256(p.read_bytes()).hexdigest() + ' -->' for p in hashes]
    args.output.write_text('\n'.join(lines))
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
