"""ap-2 first step: re-measure the raw derivation budget N and the step budget after D9 (act-phrases PLAN 11, item 4).

    uv run python docs/act-phrases/ap-2/measure_n.py

Rule (PLAN AP-0 item 4 and AP-2; spec 1.6): R is the largest raw derivation count and S the largest step count at cap
256 over the corpus; R <= 64 keeps N = 256 (64 < R < 256 gives 1,024; R >= 256 the least power of two >= 4R); 10 S <=
2,100,000 keeps the step budget (otherwise 10 S rounded up to the next 100,000).

D9 is decided as option (i) (DRI-DECISIONS-PHASE2 AP4): the refusal lives in `meaning`, and the rule table (spec 5.2)
is unchanged, so raw counts and steps are measured on draft 2's rule table as written. The instrument is the
specification's stub at the pinned plan commit (draft 1; its 5.2 and 5.3 are byte-identical in draft 2), read with
`git show`, checked against its sha256 and elaborated once with `lake env lean` against this worktree's build.

Corpus: the 22 registered phrases of `research/act-phrases/corpus.json` at the pinned commit, with their registered
vocabularies, plus the M1 act phrases AP-0 left out (u039, u041, u082, u085, u086, u091, u106, u108). The phrases and
fixed phrases are not written by the person measuring; the M1 frames are, by the rule below. So this is not the
re-measurement PLAN 11's deferred item 5 asks for (vocabularies written by someone other than the person measuring),
and the values it gives (`fixed` in the evidence: the value AP-0's rule gives) stay provisional:

* phrases and fixed phrases: u039, u041, u085 and u106 are the specification's fixtures A1, A16, A2 and A3 (11.1),
  with the fixed phrases the specification declares; u082, u086, u091 and u108 are the pilot declaration of each
  unit's entitlement (AP-0's re-try documents, `udhr-retry/<unit>.entitlement.ve.md`), the words after
  "is entitled" or "has the right", from its `verbalisation`, else its `description` with "The person" read as `{0}`.
  The pilots declare no fixed phrase for those four, so they have none.
* frames: no pilot declares frames yet, so each row's frame is generated by one fixed rule, `rule_frames`, written
  before the run: the head is the run of words after `{0}` and any leading "to" / "be", up to the first word of the
  closed preposition list `PREPOSITIONS`, a comma, a join word, a slot or a fixed phrase (lower-cased); every
  preposition of the list that occurs after the head is a marker. Two variants, both measured: `mods` (every such
  preposition a modifier marker, which gives the edge rules the most room: an upper reading of R) and `args` (every
  such preposition an argument marker). No adverbs and no direct object are declared (the head runs up to the first
  preposition). A row whose head is empty has no frame and so no derivation; it is recorded, not dropped.

Writes docs/act-phrases/ap-2/evidence/n-measurement.json. No model call; nothing under lean/ is written.
"""
import hashlib
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PIN = "bb5b2f90d58776d5e13d50e07a393dea8c791218"
STUB = "research/act-phrases/stub/SpecStubs_act-phrases.lean"
STUB_SHA256 = "6e33f85c0727c5aa3fd8d9b3975128be279f716674085acd1c3680493e32c215"
CORPUS = "research/act-phrases/corpus.json"
RETRY = "docs/research/evidence/act-phrases/udhr-retry/{}.entitlement.ve.md"
OUT = Path(__file__).resolve().parent / "evidence/n-measurement.json"
PROVISIONAL_N, PROVISIONAL_STEPS = 256, 2_100_000

PREPOSITIONS = ["about", "according", "against", "among", "at", "beyond", "by", "for", "from", "in", "including",
                "into", "of", "on", "regardless", "through", "to", "towards", "under", "until", "upon", "with",
                "without"]
JOINS = ["and", "or", "nor"]

# The specification's fixtures (docs/spec/act-phrases.md 11.1), as written there.
SPEC_ROWS = [
    ("M039", "u039", "{0} in full equality to a fair and public hearing by an independent and impartial tribunal in {1}",
     ["a fair and public hearing by an independent and impartial tribunal"], "A1"),
    ("M041", "u041", "{0} to be presumed innocent until proved guilty according to law in a public trial at which they "
     "have had all the guarantees necessary for their defence",
     ["a public trial at which they have had all the guarantees necessary for their defence"], "A16"),
    ("M085", "u085", "{0} to equal pay for equal work without any discrimination", ["equal pay for equal work"], "A2"),
    ("M106", "u106", "{0} to the protection of the moral and material interests resulting from {1}",
     ["the moral and material interests"], "A3"),
]
PILOT_UNITS = [("M082", "u082"), ("M086", "u086"), ("M091", "u091"), ("M108", "u108")]
FORMS = ["is entitled ", "has the right "]


def git_show(path):
    return subprocess.run(["git", "show", f"{PIN}:{path}"], cwd=ROOT, check=True, capture_output=True).stdout


def pilot_phrase(unit):
    text = git_show(RETRY.format(unit)).decode()
    doc = json.JSONDecoder().raw_decode(text[text.index("{"):])[0]
    preds = doc["environment"]["vocabulary"]["predicates"]
    (name, p), = [(n, p) for n, p in preds.items() if "regulated" in p]
    words = p.get("verbalisation") or p["description"].replace("The person ", "{0} ", 1)
    for form in FORMS:
        if words.startswith("{0} " + form):
            return name, "{0} " + words[len("{0} " + form):]
    sys.exit(f"{unit}: no form in {words!r}")


def rule_frames(phrase, fixed, variant):
    """The one frame of a row, by the rule in the module docstring; [] when the head is empty."""
    for f in fixed:
        phrase = phrase.replace(f, " \x00 ")
    toks = phrase.replace(",", " , ").split()[1:]
    while toks and toks[0] in ("to", "be"):
        toks = toks[1:]
    head = []
    for t in toks:
        if t.lower() in PREPOSITIONS or t in (",", "\x00") or t.lower() in JOINS or t.startswith("{"):
            break
        head.append(t.lower())
    if not head:
        return []
    rest = toks[len(head):]
    preps = list(dict.fromkeys(t.lower() for t in rest if t.lower() in PREPOSITIONS))
    return [[" ".join(head), preps, [], []] if variant == "args" else [" ".join(head), [], [], preps]]


def lean_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lean_list(xs):
    return "[" + ", ".join(lean_str(x) for x in xs) + "]"


def vocab(frames, adverbs):
    fs = ", ".join(f"⟨{lean_list(h.split())}, {lean_list(m)}, {lean_list(s)}, {lean_list(mods)}⟩"
                   for h, m, s, mods in frames)
    return f"(⟨[{fs}], {lean_list(adverbs)}⟩ : Vocab)"


MEASURE = r'''

/-! ## ap-2: measurement (generated by docs/act-phrases/ap-2/measure_n.py; not part of the specification's stub) -/

namespace VE.Acts.Fix
open VE.Acts.Lexical (Tok lex decodeFixed)

def apBigCap : Nat := 1000000
def apBigBudget : Nat := 1000000000
def apQ (s : String) : String := "\"" ++ (((s.replace "\\" "\\\\").replace "\"" "\\\"").replace "\n" " ") ++ "\""
def apN : Option Nat → String
  | some n => toString n
  | none => "null"

def apRow (id : String) (V : Vocab) (fx : List String) (s : String) : String :=
  let lexed := lex fx s
  let ts := (lexed.toOption.getD []).toArray
  let B := build V
  let G := grammarOf B
  let μ : VE.Grammar.Tree Tok → Option Act := fun t => match meaningWith V B () t with
    | .ok (A, _, _) => some A
    | .error _ => none
  let all := VE.Grammar.parse G apBigCap apBigBudget ts
  "APROW {" ++
    "\"id\": " ++ apQ id ++
    ", \"bytes\": " ++ toString s.utf8ByteSize ++
    ", \"tokens\": " ++ toString ts.size ++
    ", \"lex_ok\": " ++ toString lexed.toBool ++
    ", \"fixed_ok\": " ++ toString (decodeFixed fx).toBool ++
    ", \"frames_ok_draft1\": " ++ toString (framesOk V) ++
    ", \"raw\": " ++ apN (all.map (·.length)) ++
    ", \"meanings_before_d9\": " ++ apN (all.map (fun ts => (firsts (ts.filterMap μ)).length)) ++
    ", \"steps_cap_256\": " ++ apN (G.prepare.steps rawCap apBigBudget ts) ++
    ", \"steps_uncapped\": " ++ apN (G.prepare.steps apBigCap apBigBudget ts) ++
    "}"

'''


def canonical_markers(frames):
    """Draft 2's added condition of `framesOk` (spec 1.4, SR1): every marker but "" and every modifier canonical."""
    return all(m.split() and m == " ".join(m.split())
               for _h, markers, _s, mods in frames for m in [x for x in markers if x != ""] + list(mods))


def main():
    stub = git_show(STUB)
    digest = hashlib.sha256(stub).hexdigest()
    if digest != STUB_SHA256:
        sys.exit(f"stub changed: {digest}")
    corpus = json.loads(git_show(CORPUS))
    rows = []
    for r in corpus["rows"]:
        rows.append({"id": r["id"], "unit": r["unit"], "kind": r["kind"], "phrase": r["phrase"], "fixed": r["fixed"],
                     "frames": r["frames"], "adverbs": r["adverbs"], "source": f"{CORPUS} (registered)"})
    m1 = [(i, u, p, fx, f"docs/spec/act-phrases.md 11.1 {a}") for i, u, p, fx, a in SPEC_ROWS]
    for i, u in PILOT_UNITS:
        name, phrase = pilot_phrase(u)
        m1.append((i, u, phrase, [], f"{RETRY.format(u)} predicate {name}"))
    for i, u, phrase, fx, src in sorted(m1):
        for variant in ("mods", "args"):
            rows.append({"id": f"{i}{variant[0]}", "unit": u, "kind": f"m1-{variant}", "phrase": phrase, "fixed": fx,
                         "frames": rule_frames(phrase, fx, variant), "adverbs": [], "source": src})
    lines = [MEASURE] + [f"#eval IO.println (apRow {lean_str(r['id'])} {vocab(r['frames'], r['adverbs'])} "
                         f"{lean_list(r['fixed'])} {lean_str(r['phrase'])})" for r in rows]
    lines.append("\nend VE.Acts.Fix\n")
    env = dict(os.environ, PATH=str(Path.home() / ".elan/bin") + os.pathsep + os.environ["PATH"])
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "Ap2Measure.lean"
        src.write_text(stub.decode() + "".join(x + "\n" for x in lines))
        proc = subprocess.run(["lake", "env", "lean", str(src)], cwd=ROOT / "lean", env=env, capture_output=True,
                              text=True)
    measured = {json.loads(ln[6:])["id"]: json.loads(ln[6:]) for ln in proc.stdout.splitlines()
                if ln.startswith("APROW ")}
    other = [ln for ln in (proc.stdout + proc.stderr).splitlines() if ln and not ln.startswith("APROW ")]
    if proc.returncode != 0 or other or len(measured) != len(rows):
        print("\n".join(other[:80]))
        sys.exit(f"lean failed (exit {proc.returncode}); {len(measured)} of {len(rows)} rows")
    for r in rows:
        r.update(measured[r["id"]])
        r["frames_canonical_draft2"] = canonical_markers(r["frames"])
    unfinished = [r["id"] for r in rows if r["raw"] is None or r["steps_cap_256"] is None]
    R = max(r["raw"] or 0 for r in rows)
    S = max(r["steps_cap_256"] or 0 for r in rows)
    if unfinished:
        n_value = s_value = None
        n_verdict = s_verdict = "FAIL: a parse did not finish"
    else:
        n_value, n_verdict = ((PROVISIONAL_N, "PASS") if R <= 64 else (1024, "FAIL") if R < 256
                              else (1 << (4 * R - 1).bit_length(), "FAIL"))
        s_value, s_verdict = ((PROVISIONAL_STEPS, "PASS") if 10 * S <= PROVISIONAL_STEPS
                              else (-(-10 * S // 100_000) * 100_000, "FAIL"))
    result = {
        "rule": "docs/spec/act-phrases-PLAN.md AP-0 item 4 and AP-2; docs/spec/act-phrases.md 1.6",
        "d9": "option (i), the refusal in `meaning` (DRI-DECISIONS-PHASE2 AP4): the rule table is unchanged",
        "pinned_commit": PIN, "stub": STUB, "stub_sha256": digest, "corpus": CORPUS,
        "prepositions": PREPOSITIONS, "lean_returncode": proc.returncode,
        "rows_total": len(rows), "rows_registered": len(corpus["rows"]), "unfinished": unfinished,
        "R_max_raw": R, "R_rows": [r["id"] for r in rows if r["raw"] == R],
        "S_max_steps_cap_256": S, "S_rows": [r["id"] for r in rows if r["steps_cap_256"] == S],
        "N": {"provisional": PROVISIONAL_N, "fixed": n_value, "verdict": n_verdict},
        "step_budget": {"provisional": PROVISIONAL_STEPS, "fixed": s_value, "verdict": s_verdict},
        "rows": rows,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(result, indent=1, ensure_ascii=False) + "\n")
    for r in rows:
        print(f"{r['id']:9} {r['bytes']:4}B tok={r['tokens']:3} raw={r['raw']} mean={r['meanings_before_d9']} "
              f"steps256={r['steps_cap_256']} fok={r['frames_ok_draft1']}/{r['frames_canonical_draft2']} "
              f"frames={r['frames']}")
    print(json.dumps({k: result[k] for k in ("R_max_raw", "R_rows", "S_max_steps_cap_256", "S_rows", "N",
                                             "step_budget", "unfinished")}))


if __name__ == "__main__":
    main()
