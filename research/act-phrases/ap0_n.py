"""AP-0 item 4: measure the raw derivation budget N and the step budget (rule: docs/research/act-phrases-phase1.md 1.5).

    uv run python research/act-phrases/ap0_n.py

The instrument is the specification's stub (draft 1; its rule table 5.2 and meaning 5.3 are byte-identical in draft 2),
copied verbatim to research/act-phrases/stub/ and checked against its sha256 here. This script appends a measurement
section generated from research/act-phrases/corpus.json, elaborates the whole file once with `lake env lean` against
this worktree's Lean build (which also re-runs the stub's own 161 `#guard`s), and writes
docs/research/evidence/act-phrases/n-measurement.json. No model call; nothing under lean/ is written.
"""
import hashlib
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
STUB = HERE / "stub/SpecStubs_act-phrases.lean"
STUB_SHA256 = "6e33f85c0727c5aa3fd8d9b3975128be279f716674085acd1c3680493e32c215"
OUT = ROOT / "docs/research/evidence/act-phrases/n-measurement.json"
PROVISIONAL_N, PROVISIONAL_STEPS = 256, 2_100_000


def lean_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lean_list(xs):
    return "[" + ", ".join(lean_str(x) for x in xs) + "]"


def vocab(frames, adverbs):
    fs = ", ".join(f"fr {lean_str(h)} {lean_list(m)} {lean_list(s)} {lean_list(mods)}" for h, m, s, mods in frames)
    return f"(⟨[{fs}], {lean_list(adverbs)}⟩ : Vocab)"


MEASURE = r'''

/-! ## AP-0 item 4: measurement (generated by research/act-phrases/ap0_n.py; not part of the specification's stub) -/

namespace VE.Acts.Fix
open VE.Acts.Lexical (Tok lex decodeFixed)

def ap0BigCap : Nat := 1000000
def ap0BigBudget : Nat := 1000000000
def ap0Q (s : String) : String := "\"" ++ (((s.replace "\\" "\\\\").replace "\"" "\\\"").replace "\n" " ") ++ "\""
def ap0N : Option Nat → String
  | some n => toString n
  | none => "null"

def ap0Row (id : String) (V : Vocab) (fx : List String) (s : String) : String :=
  let lexed := lex fx s
  let lexErr := match lexed with
    | .error m => ap0Q m
    | .ok _ => "null"
  let fixedErr := match decodeFixed fx with
    | .error m => ap0Q m
    | .ok _ => "null"
  let ts := (lexed.toOption.getD []).toArray
  let B := build V
  let G := grammarOf B
  let μ : VE.Grammar.Tree Tok → Option Act := fun t => match meaningWith V B () t with
    | .ok (A, _, _) => some A
    | .error _ => none
  let all := VE.Grammar.parse G ap0BigCap ap0BigBudget ts
  let listed := match readings V rawCap stepBudget ts with
    | .ok As => "\"ok " ++ toString As.length ++ "\""
    | .limit => "\"limit\""
  -- Exploratory (not part of the bar): the meanings themselves, when there are at most 4.
  let trees := match all with
    | some ts => let ms := firsts (ts.filterMap μ)
        if ms.length ≤ 4 then "[" ++ ", ".intercalate (ms.map (fun A => ap0Q ((repr A).pretty 100000))) ++ "]"
        else "null"
    | none => "null"
  "AP0ROW {" ++
    "\"id\": " ++ ap0Q id ++
    ", \"bytes\": " ++ toString s.utf8ByteSize ++
    ", \"tokens\": " ++ toString ts.size ++
    ", \"lex_error\": " ++ lexErr ++
    ", \"fixed_error\": " ++ fixedErr ++
    ", \"frames_ok_draft1\": " ++ toString (framesOk V) ++
    ", \"raw\": " ++ ap0N (all.map (·.length)) ++
    ", \"raw_with_meaning\": " ++ ap0N (all.map (fun ts => (ts.filterMap μ).length)) ++
    ", \"meanings\": " ++ ap0N (all.map (fun ts => (firsts (ts.filterMap μ)).length)) ++
    ", \"readings_at_product_limits\": " ++ listed ++
    ", \"steps_cap_256\": " ++ ap0N (G.prepare.steps rawCap ap0BigBudget ts) ++
    ", \"steps_uncapped\": " ++ ap0N (G.prepare.steps ap0BigCap ap0BigBudget ts) ++
    ", \"exploratory_meanings\": " ++ trees ++
    "}"

'''


def canonical_markers(frames):
    """Draft 2's added condition (spec 1.4, SR1): every marker but "" and every modifier marker canonical, non-empty."""
    for _head, markers, _split, mods in frames:
        for m in [m for m in markers if m != ""] + list(mods):
            if not m.split() or m != " ".join(m.split()):
                return False
    return True


def main():
    digest = hashlib.sha256(STUB.read_bytes()).hexdigest()
    if digest != STUB_SHA256:
        sys.exit(f"stub changed: {digest}")
    corpus = json.loads((HERE / "corpus.json").read_text())
    rows = {r["id"]: r for r in corpus["rows"]}
    lines = [MEASURE]
    for r in corpus["rows"]:
        lines.append(f"#eval IO.println (ap0Row {lean_str(r['id'])} {vocab(r['frames'], r['adverbs'])} "
                     f"{lean_list(r['fixed'])} {lean_str(r['phrase'])})")
    stress = corpus["stress"]
    v5 = [["seek", [""], [], ["in"]], ["enjoy", [""], [], ["in"]]]
    for k in stress["k"]:
        phrase = "{0} to seek and to enjoy asylum" + "".join(" in " + c for c in stress["cities"][:k])
        lines.append(f"#eval IO.println (ap0Row {lean_str(f'L{k}')} {vocab(v5, [])} "
                     f"{lean_list(stress['cities'])} {lean_str(phrase)})")
    lines.append("\nend VE.Acts.Fix\n")
    env = dict(os.environ, PATH=str(Path.home() / ".elan/bin") + os.pathsep + os.environ["PATH"])
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "Ap0Measure.lean"
        src.write_text(STUB.read_text() + "".join(x + "\n" for x in lines))
        proc = subprocess.run(["lake", "env", "lean", str(src)], cwd=ROOT / "lean", env=env, capture_output=True,
                              text=True)
    measured = [json.loads(ln[len("AP0ROW "):]) for ln in proc.stdout.splitlines() if ln.startswith("AP0ROW ")]
    other = [ln for ln in (proc.stdout + proc.stderr).splitlines() if ln and not ln.startswith("AP0ROW ")]
    if proc.returncode != 0 or other:
        print("\n".join(other[:80]))
    if proc.returncode != 0 or not measured:
        sys.exit(f"lean failed (exit {proc.returncode}); {len(measured)} rows")
    for m in measured:
        r = rows.get(m["id"])
        m["kind"] = r["kind"] if r else "stress"
        m["unit"] = r["unit"] if r else None
        m["frames_canonical_draft2"] = canonical_markers(r["frames"]) if r else True
    corpus_rows = [m for m in measured if m["kind"] != "stress"]
    unfinished = [m["id"] for m in corpus_rows if m["raw"] is None or m["steps_cap_256"] is None]
    R = max((m["raw"] or 0) for m in corpus_rows)
    S = max((m["steps_cap_256"] or 0) for m in corpus_rows)
    if unfinished:
        n_rule, n_verdict, s_verdict, n_value, s_value = "a parse did not finish", "FAIL", "FAIL", None, None
    else:
        if R <= 64:
            n_value, n_verdict = PROVISIONAL_N, "PASS"
        elif R < 256:
            n_value, n_verdict = 1024, "FAIL"
        else:
            n_value, n_verdict = 1 << (4 * R - 1).bit_length(), "FAIL"
        n_rule = "1.5"
        if 10 * S <= PROVISIONAL_STEPS:
            s_value, s_verdict = PROVISIONAL_STEPS, "PASS"
        else:
            s_value, s_verdict = -(-10 * S // 100_000) * 100_000, "FAIL"
    result = {
        "rule": "docs/research/act-phrases-phase1.md 1.5", "stub": str(STUB.relative_to(ROOT)), "stub_sha256": digest,
        "lean_returncode": proc.returncode, "lean_other_output": other[:200],
        "corpus_rows": len(corpus_rows), "unfinished": unfinished,
        "R_max_raw": R, "R_rows": [m["id"] for m in corpus_rows if m["raw"] == R],
        "S_max_steps_cap_256": S, "S_rows": [m["id"] for m in corpus_rows if m["steps_cap_256"] == S],
        "N": {"provisional": PROVISIONAL_N, "fixed": n_value, "verdict": n_verdict, "rule": n_rule},
        "step_budget": {"provisional": PROVISIONAL_STEPS, "fixed": s_value, "verdict": s_verdict},
        "raw_above_meanings": [m["id"] for m in corpus_rows if (m["raw"] or 0) > (m["meanings"] or 0)],
        "no_reading": [m["id"] for m in corpus_rows if m["meanings"] == 0],
        "rows": measured,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(result, indent=1, ensure_ascii=False) + "\n")
    for m in measured:
        print(f"{m['id']:9} {m['bytes']:4}B tok={m['tokens']:3} raw={m['raw']} mean={m['meanings']} "
              f"list={m['readings_at_product_limits']} steps256={m['steps_cap_256']} stepsAll={m['steps_uncapped']} "
              f"fok={m['frames_ok_draft1']}/{m['frames_canonical_draft2']} lex={m['lex_error']} fixed={m['fixed_error']}")
    print(json.dumps({k: result[k] for k in ("lean_returncode", "R_max_raw", "R_rows", "S_max_steps_cap_256", "S_rows",
                                             "N", "step_budget", "raw_above_meanings", "no_reading", "unfinished")}))


if __name__ == "__main__":
    main()
